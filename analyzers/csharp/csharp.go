// Package csharp analyzes C# source with tree-sitter. It parses files and never
// builds or runs them.
package csharp

import (
	"bytes"
	"context"
	"path"
	"strings"

	ts "github.com/tree-sitter/go-tree-sitter"

	"github.com/rburns629/urfluency/analysis"
	"github.com/rburns629/urfluency/parsing"
)

func init() { analysis.Register(Analyzer{}) }

// Analyzer implements analysis.Analyzer for C#.
type Analyzer struct{}

func (Analyzer) Language() string     { return "csharp" }
func (Analyzer) Extensions() []string { return []string{".cs"} }

// SkipPath excludes build output and files generated by the compiler, designers,
// source generators, and Entity Framework migrations.
func (Analyzer) SkipPath(p string) bool {
	if parsing.InDir(p, "bin", "obj") {
		return true
	}
	base := strings.ToLower(path.Base(p))
	for _, s := range []string{".designer.cs", ".g.cs", ".g.i.cs", ".assemblyattributes.cs"} {
		if strings.HasSuffix(base, s) {
			return true
		}
	}
	if base == "assemblyinfo.cs" {
		return true
	}
	// dotnet ef writes Migrations/<14-digit timestamp>_Name.cs and a model snapshot.
	return parsing.InDir(p, "Migrations") && (strings.HasSuffix(base, "modelsnapshot.cs") || isMigrationName(base))
}

func isMigrationName(base string) bool {
	if len(base) < 16 || base[14] != '_' {
		return false
	}
	for _, r := range base[:14] {
		if r < '0' || r > '9' {
			return false
		}
	}
	return true
}

// Skip excludes generated files, which carry an <auto-generated> header comment.
func (a Analyzer) Skip(f analysis.File) bool {
	if a.SkipPath(f.Path) {
		return true
	}
	head := bytes.ToLower(f.Content[:min(len(f.Content), 1024)])
	return bytes.Contains(head, []byte("<auto-generated")) || bytes.Contains(head, []byte("<autogenerated"))
}

// complexity names the C# grammar's nodes for cognitive complexity. The grammar
// has no else clause node: an else if is an if_statement directly inside another,
// so it is not counted again, and a plain else adds nothing.
var complexity = parsing.ComplexitySyntax{
	Functions: set("method_declaration", "constructor_declaration", "destructor_declaration", "operator_declaration",
		"conversion_operator_declaration", "accessor_declaration", "local_function_statement", "lambda_expression",
		"anonymous_method_expression"),
	Structures: set("if_statement", "for_statement", "foreach_statement", "while_statement", "do_statement",
		"switch_statement", "switch_expression", "catch_clause", "conditional_expression"),
	ElseToken:  "else",
	Logical:    "binary_expression",
	LogicalOps: set("&&", "||", "??"),
	Call:       "invocation_expression",
	Self:       []string{"this"},
}

func set(kinds ...string) map[string]bool {
	m := make(map[string]bool, len(kinds))
	for _, k := range kinds {
		m[k] = true
	}
	return m
}

// Analyze applies every C# rule to each file.
func (Analyzer) Analyze(ctx context.Context, files []analysis.File) ([]analysis.Finding, error) {
	var findings []analysis.Finding
	for _, f := range files {
		if err := ctx.Err(); err != nil {
			return nil, err
		}
		tree, err := parsing.Parse(parsing.CSharp, f.Content)
		if err != nil {
			continue
		}
		c := checker{tree: tree, path: f.Path, frameworks: frameworksOf(tree)}
		parsing.Walk(tree.Root(), c.visit)
		parsing.Walk(tree.Root(), c.visitIdioms)
		if !analysis.IsTestPath(f.Path) {
			for _, fn := range parsing.Cognitive(tree, complexity) {
				if fn.Complexity > parsing.CognitiveThreshold {
					c.findings = append(c.findings, analysis.Finding{Rule: "clean.cognitive-complexity", Path: f.Path, Line: fn.Line})
				}
			}
		}
		tree.Close()
		findings = append(findings, c.findings...)
	}
	return findings, nil
}

type checker struct {
	tree       *parsing.Tree
	path       string
	frameworks map[string]bool
	findings   []analysis.Finding
}

// text returns a node's source text, or "" for a missing node.
func (c *checker) text(n *ts.Node) string {
	if n == nil {
		return ""
	}
	return c.tree.Text(n)
}

func (c *checker) report(rule string, n *ts.Node) {
	c.findings = append(c.findings, analysis.Finding{Rule: rule, Path: c.path, Line: parsing.Line(n)})
}

func (c *checker) visit(n *ts.Node) bool {
	switch n.Kind() {
	case "object_creation_expression":
		c.checkCreation(n)
	case "invocation_expression":
		c.checkInvocation(n)
	case "member_access_expression":
		if name := n.ChildByFieldName("name"); name != nil && c.tree.Text(name) == "Result" && c.isTask(n.ChildByFieldName("expression")) {
			c.report("csharp.blocking-on-task", n)
		}
	case "assignment_expression":
		c.checkAssignment(n)
	case "method_declaration", "local_function_statement":
		c.checkAsyncVoid(n)
	case "catch_clause":
		c.checkCatch(n)
	case "identifier":
		if c.tree.Text(n) == "dynamic" && isTypePosition(n) {
			c.report("csharp.dynamic-type", n)
		}
	}
	return true
}

// lastName returns the final segment of a possibly qualified name.
func (c *checker) lastName(n *ts.Node) string {
	text := c.text(n)
	return text[strings.LastIndex(text, ".")+1:]
}

// memberName returns the method name an invocation calls, such as "Where" for
// xs.Where(...) or "Format" for string.Format(...).
func (c *checker) memberName(call *ts.Node) string {
	fn := call.ChildByFieldName("function")
	if fn == nil {
		return ""
	}
	switch fn.Kind() {
	case "member_access_expression":
		return c.lastName(fn.ChildByFieldName("name"))
	case "identifier":
		return c.tree.Text(fn)
	case "generic_name":
		if fn.NamedChildCount() > 0 {
			return c.tree.Text(fn.NamedChild(0))
		}
	}
	return ""
}

// firstArgument returns the expression of a call's first argument.
func firstArgument(call *ts.Node) *ts.Node {
	args := call.ChildByFieldName("arguments")
	if args == nil {
		return nil
	}
	for _, a := range parsing.NamedChildren(args) {
		if a.Kind() == "argument" && a.NamedChildCount() > 0 {
			return a.NamedChild(a.NamedChildCount() - 1)
		}
	}
	return nil
}

var sqlCommandTypes = map[string]bool{
	"SqlCommand": true, "SqliteCommand": true, "NpgsqlCommand": true, "MySqlCommand": true,
	"OracleCommand": true, "OleDbCommand": true, "OdbcCommand": true, "SqlDataAdapter": true,
}

var sqlRawMethods = map[string]bool{
	"FromSqlRaw": true, "ExecuteSqlRaw": true, "ExecuteSqlRawAsync": true, "SqlQueryRaw": true,
}

var insecureSerializers = map[string]bool{
	"BinaryFormatter": true, "SoapFormatter": true, "NetDataContractSerializer": true,
	"LosFormatter": true, "ObjectStateFormatter": true,
}

func (c *checker) checkCreation(n *ts.Node) {
	typeName := c.lastName(n.ChildByFieldName("type"))
	switch {
	case insecureSerializers[typeName]:
		c.report("csharp.binary-formatter", n)
	case sqlCommandTypes[typeName] && c.builtString(firstArgument(n)):
		c.report("csharp.sql-string-built", n)
	}
}

func (c *checker) checkInvocation(n *ts.Node) {
	name := c.memberName(n)
	switch {
	case sqlRawMethods[name] && c.builtString(firstArgument(n)):
		c.report("csharp.sql-string-built", n)
	case name == "GetResult":
		if fn := n.ChildByFieldName("function"); fn != nil && fn.Kind() == "member_access_expression" {
			if recv := fn.ChildByFieldName("expression"); recv != nil && recv.Kind() == "invocation_expression" && c.memberName(recv) == "GetAwaiter" {
				c.report("csharp.blocking-on-task", n)
			}
		}
	case name == "Wait":
		if fn := n.ChildByFieldName("function"); fn != nil && fn.Kind() == "member_access_expression" && c.isTask(fn.ChildByFieldName("expression")) {
			c.report("csharp.blocking-on-task", n)
		}
	case name == "WaitAll" || name == "WaitAny":
		if fn := n.ChildByFieldName("function"); fn != nil && c.tree.Text(fn) == "Task."+name {
			c.report("csharp.blocking-on-task", n)
		}
	}
}

// isTask reports whether an expression is visibly a task: a call to a method
// named *Async or to Task.Run, Task.WhenAll, or Task.WhenAny. Other receivers of
// .Result or .Wait() are left alone, since many types have a Result property.
func (c *checker) isTask(n *ts.Node) bool {
	if n == nil || n.Kind() != "invocation_expression" {
		return false
	}
	if strings.HasSuffix(c.memberName(n), "Async") {
		return true
	}
	fn := n.ChildByFieldName("function")
	if fn == nil {
		return false
	}
	switch c.tree.Text(fn) {
	case "Task.Run", "Task.WhenAll", "Task.WhenAny", "Task.Factory.StartNew":
		return true
	}
	return false
}

// builtString reports whether an expression builds text from values at run time:
// an interpolated string with holes, concatenation involving a non-literal, or
// string.Format and string.Concat.
func (c *checker) builtString(n *ts.Node) bool {
	if n == nil {
		return false
	}
	switch n.Kind() {
	case "interpolated_string_expression":
		for _, child := range parsing.NamedChildren(n) {
			if child.Kind() == "interpolation" {
				return true
			}
		}
	case "parenthesized_expression":
		return n.NamedChildCount() == 1 && c.builtString(n.NamedChild(0))
	case "binary_expression":
		op := n.ChildByFieldName("operator")
		return op != nil && op.Kind() == "+" && c.hasString(n) && !isConstant(n)
	case "invocation_expression":
		if fn := n.ChildByFieldName("function"); fn != nil {
			switch c.tree.Text(fn) {
			case "string.Format", "String.Format", "string.Concat", "String.Concat":
				return true
			}
		}
	}
	return false
}

var stringKinds = map[string]bool{
	"string_literal": true, "verbatim_string_literal": true, "raw_string_literal": true, "interpolated_string_expression": true,
}

func (c *checker) hasString(n *ts.Node) bool {
	if stringKinds[n.Kind()] {
		return true
	}
	if n.Kind() != "binary_expression" && n.Kind() != "parenthesized_expression" {
		return false
	}
	for _, child := range parsing.NamedChildren(n) {
		if c.hasString(child) {
			return true
		}
	}
	return false
}

// isConstant reports whether a concatenation joins only literals.
func isConstant(n *ts.Node) bool {
	switch n.Kind() {
	case "string_literal", "verbatim_string_literal", "raw_string_literal", "integer_literal", "character_literal":
		return true
	case "binary_expression", "parenthesized_expression":
		for _, child := range parsing.NamedChildren(n) {
			if !isConstant(child) {
				return false
			}
		}
		return true
	}
	return false
}

var certificateCallbacks = map[string]bool{
	"ServerCertificateCustomValidationCallback": true, "ServerCertificateValidationCallback": true,
	"RemoteCertificateValidationCallback": true,
}

func (c *checker) checkAssignment(n *ts.Node) {
	left, right := n.ChildByFieldName("left"), n.ChildByFieldName("right")
	if left == nil || right == nil {
		return
	}
	target := left
	if left.Kind() == "member_access_expression" {
		target = left.ChildByFieldName("name")
	}
	if target == nil {
		return
	}
	switch name := c.tree.Text(target); {
	case certificateCallbacks[name] && c.acceptsAll(right):
		c.report("csharp.certificate-validation-disabled", n)
	case name == "CommandText" && c.builtString(right):
		c.report("csharp.sql-string-built", n)
	}
}

// acceptsAll reports whether a validation callback returns true unconditionally.
func (c *checker) acceptsAll(n *ts.Node) bool {
	switch n.Kind() {
	case "lambda_expression":
		body := n.ChildByFieldName("body")
		return body != nil && (c.isTrue(body) || c.returnsTrue(body))
	case "anonymous_method_expression":
		for _, child := range parsing.NamedChildren(n) {
			if child.Kind() == "block" {
				return c.returnsTrue(child)
			}
		}
	case "member_access_expression", "identifier":
		return strings.HasSuffix(c.tree.Text(n), "DangerousAcceptAnyServerCertificateValidator")
	}
	return false
}

func (c *checker) isTrue(n *ts.Node) bool {
	return n.Kind() == "boolean_literal" && c.tree.Text(n) == "true"
}

// returnsTrue reports whether a block is exactly "return true;".
func (c *checker) returnsTrue(block *ts.Node) bool {
	if block.Kind() != "block" || block.NamedChildCount() != 1 {
		return false
	}
	ret := block.NamedChild(0)
	return ret.Kind() == "return_statement" && ret.NamedChildCount() == 1 && c.isTrue(ret.NamedChild(0))
}

func (c *checker) hasModifier(n *ts.Node, modifier string) bool {
	for _, child := range parsing.NamedChildren(n) {
		if child.Kind() == "modifier" && c.tree.Text(child) == modifier {
			return true
		}
	}
	return false
}

// returnType returns a method's or local function's return type.
func returnType(n *ts.Node) *ts.Node {
	if r := n.ChildByFieldName("returns"); r != nil {
		return r
	}
	return n.ChildByFieldName("type")
}

// unityMessages are MonoBehaviour methods Unity calls by name, where async void
// is the only way to await.
var unityMessages = map[string]bool{
	"Awake": true, "Start": true, "Update": true, "LateUpdate": true, "FixedUpdate": true,
	"OnEnable": true, "OnDisable": true, "OnDestroy": true,
}

// checkAsyncVoid flags async void methods other than event handlers, overrides
// (whose signature is fixed by the base class), and Unity messages.
func (c *checker) checkAsyncVoid(n *ts.Node) {
	ret := returnType(n)
	if ret == nil || c.tree.Text(ret) != "void" || !c.hasModifier(n, "async") || c.hasModifier(n, "override") {
		return
	}
	if name := n.ChildByFieldName("name"); name != nil && c.frameworks["unity"] && unityMessages[c.tree.Text(name)] {
		return
	}
	if params := n.ChildByFieldName("parameters"); params != nil {
		ps := parsing.NamedChildren(params)
		if len(ps) == 2 && strings.HasSuffix(c.text(ps[1].ChildByFieldName("type")), "EventArgs") {
			return
		}
	}
	c.report("csharp.async-void", n)
}

// checkCatch flags empty catch blocks that catch everything or Exception and
// have no filter. A comment in the block counts as a stated reason.
func (c *checker) checkCatch(n *ts.Node) {
	var body *ts.Node
	for _, child := range parsing.NamedChildren(n) {
		switch child.Kind() {
		case "catch_filter_clause":
			return
		case "catch_declaration":
			if t := c.text(child.ChildByFieldName("type")); t != "Exception" && t != "System.Exception" {
				return
			}
		case "block":
			body = child
		}
	}
	if body != nil && body.NamedChildCount() == 0 {
		c.report("csharp.empty-catch", n)
	}
}

// isTypePosition reports whether an identifier is used as a type: a declared
// type, return type, cast, or type argument.
func isTypePosition(n *ts.Node) bool {
	parent := n.Parent()
	if parent == nil {
		return false
	}
	switch parent.Kind() {
	case "type_argument_list", "array_type", "nullable_type":
		return true
	}
	for _, field := range []string{"type", "returns"} {
		if f := parent.ChildByFieldName(field); f != nil && f.Id() == n.Id() {
			return true
		}
	}
	return false
}
