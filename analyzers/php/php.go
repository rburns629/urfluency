// Package php analyzes PHP source with tree-sitter. It parses files and never
// runs them.
package php

import (
	"bytes"
	"context"
	"path"
	"sort"
	"strings"

	ts "github.com/tree-sitter/go-tree-sitter"

	"github.com/rburns629/urfluency/analysis"
	"github.com/rburns629/urfluency/parsing"
)

func init() { analysis.Register(Analyzer{}) }

// Analyzer implements analysis.Analyzer for PHP.
type Analyzer struct{}

func (Analyzer) Language() string { return "php" }

// Extensions include .phtml, the standard extension for PHP view templates in
// Laminas (Zend), Magento, and plain PHP projects: it is PHP with HTML around
// <?php blocks, which the grammar parses like any .php file.
func (Analyzer) Extensions() []string { return []string{".php", ".phtml"} }

// SkipPath excludes Composer dependencies and framework caches, which hold
// compiled templates and generated containers: Laravel's storage/framework
// and bootstrap/cache, and Symfony's var/cache.
func (Analyzer) SkipPath(p string) bool {
	if parsing.InDir(p, "vendor", "node_modules") {
		return true
	}
	dir := "/" + path.Dir(p) + "/"
	return strings.Contains(dir, "/storage/framework/") || strings.Contains(dir, "/bootstrap/cache/") ||
		strings.Contains(dir, "/var/cache/")
}

// generatedMarkers are lowercase header phrases of code generators.
var generatedMarkers = [][]byte{
	[]byte("do not edit"), []byte("@generated"), []byte("code generated"), []byte("generated by"),
	[]byte("auto-generated"), []byte("automatically generated"), []byte("this file was generated"),
}

// Skip excludes dependencies, caches, Blade templates, and files whose header
// marks them as generated. Blade (.blade.php) is Laravel's template language,
// not PHP: its directives and {{ }} echoes are plain text to the grammar.
func (a Analyzer) Skip(f analysis.File) bool {
	if a.SkipPath(f.Path) || strings.HasSuffix(f.Path, ".blade.php") {
		return true
	}
	head := f.Content
	if len(head) > 512 {
		head = head[:512]
	}
	head = bytes.ToLower(head)
	for _, m := range generatedMarkers {
		if containsWord(head, m) {
			return true
		}
	}
	return false
}

// containsWord reports whether s contains word not followed by a letter, so
// @generated matches but Doctrine's @GeneratedValue does not.
func containsWord(s, word []byte) bool {
	for i := bytes.Index(s, word); i >= 0; {
		end := i + len(word)
		if end == len(s) || s[end] < 'a' || s[end] > 'z' {
			return true
		}
		next := bytes.Index(s[end:], word)
		if next < 0 {
			return false
		}
		i = end + next
	}
	return false
}

// complexity names this grammar's nodes for cognitive complexity. elseif is an
// else_if_clause beside the if's else_clause, so both count as hybrids; the
// two-word "else if" parses as an if_statement inside an else_clause and is
// not counted again. Ternaries (including ?:) are conditional_expression, and
// match counts like switch. "break 2" and "continue 2" jump out of several
// loops, PHP's form of a labeled jump; their level is an integer child. and,
// or, and xor are the low-precedence forms of the logical operators. Only
// plain function calls have a function field, so recursion through $this->f()
// or self::f() is not counted.
var complexity = parsing.ComplexitySyntax{
	Functions: set("function_definition", "method_declaration", "anonymous_function", "arrow_function"),
	Structures: set("if_statement", "for_statement", "foreach_statement", "while_statement", "do_statement",
		"switch_statement", "match_expression", "catch_clause", "conditional_expression"),
	Hybrids:    set("else_if_clause", "else_clause"),
	ElseClause: "else_clause",
	Logical:    "binary_expression",
	LogicalOps: set("&&", "||", "and", "or", "xor"),
	Jumps:      set("break_statement", "continue_statement"),
	Label:      "integer",
	Call:       "function_call_expression",
}

func set(kinds ...string) map[string]bool {
	m := make(map[string]bool, len(kinds))
	for _, k := range kinds {
		m[k] = true
	}
	return m
}

// Analyze applies every PHP rule and idiom to each file.
func (Analyzer) Analyze(ctx context.Context, files []analysis.File) ([]analysis.Finding, error) {
	var findings []analysis.Finding
	for _, f := range files {
		if err := ctx.Err(); err != nil {
			return nil, err
		}
		tree, err := parsing.Parse(parsing.PHP, f.Content)
		if err != nil {
			continue
		}
		c := checker{tree: tree, path: f.Path, isTest: analysis.IsTestPath(f.Path)}
		parsing.Walk(tree.Root(), c.visit)
		parsing.Walk(tree.Root(), c.visitIdioms)
		if !c.isTest {
			for _, fn := range parsing.Cognitive(tree, complexity) {
				if fn.Complexity > parsing.CognitiveThreshold {
					c.findings = append(c.findings, analysis.Finding{Rule: "clean.cognitive-complexity", Path: f.Path, Line: fn.Line})
				}
			}
		}
		tree.Close()
		findings = append(findings, c.findings...)
	}
	return findings, nil
}

// frameworkPrefixes map namespace prefixes to frameworks: yii is Yii 2 and
// Yiisoft is Yii 3. Laminas was Zend Framework, whose Zend\ namespaces older
// projects still import, and Mezzio is its middleware framework.
var frameworkPrefixes = []struct{ prefix, framework string }{
	{`Illuminate`, "laravel"},
	{`Laravel`, "laravel"},
	{`Symfony`, "symfony"},
	{`Slim`, "slim"},
	{`CodeIgniter`, "codeigniter"},
	{`yii`, "yii"},
	{`Yiisoft`, "yii"},
	{`Laminas`, "laminas"},
	{`Mezzio`, "laminas"},
	{`Zend`, "laminas"},
}

// wordpressCalls are WordPress hook and plugin functions; any wp_ function
// also marks WordPress.
var wordpressCalls = map[string]bool{
	"add_action": true, "add_filter": true, "do_action": true, "apply_filters": true,
	"register_activation_hook": true, "register_deactivation_hook": true, "add_shortcode": true,
	"get_option": true, "update_option": true, "esc_html": true, "esc_attr": true, "esc_url": true,
}

// Frameworks implements analysis.FrameworkDetector from a file's use
// statements, fully qualified names, CodeIgniter 3 base classes, and calls to
// WordPress functions.
func (Analyzer) Frameworks(f analysis.File) []string {
	tree, err := parsing.Parse(parsing.PHP, f.Content)
	if err != nil {
		return nil
	}
	defer tree.Close()
	found := map[string]bool{}
	match := func(name string) {
		name = strings.TrimPrefix(name, `\`)
		for _, p := range frameworkPrefixes {
			if name == p.prefix || strings.HasPrefix(name, p.prefix+`\`) {
				found[p.framework] = true
			}
		}
	}
	parsing.Walk(tree.Root(), func(n *ts.Node) bool {
		switch n.Kind() {
		case "namespace_use_declaration":
			for _, child := range parsing.NamedChildren(n) {
				switch child.Kind() {
				case "namespace_name": // the prefix of a group: use Symfony\{A, B}
					match(tree.Text(child))
				case "namespace_use_clause":
					if name := child.NamedChild(0); name != nil {
						match(tree.Text(name))
					}
				}
			}
			return false
		case "qualified_name":
			if strings.HasPrefix(tree.Text(n), `\`) {
				match(tree.Text(n))
			}
			return false
		case "base_clause":
			for _, name := range parsing.NamedChildren(n) {
				if t := tree.Text(name); t == "CI_Controller" || t == "CI_Model" {
					found["codeigniter"] = true
				}
			}
		case "function_call_expression":
			if fn := n.ChildByFieldName("function"); fn != nil && fn.Kind() == "name" {
				if name := strings.ToLower(tree.Text(fn)); wordpressCalls[name] || strings.HasPrefix(name, "wp_") {
					found["wordpress"] = true
				}
			}
		}
		return true
	})
	out := make([]string, 0, len(found))
	for fw := range found {
		out = append(out, fw)
	}
	sort.Strings(out)
	return out
}

type checker struct {
	tree     *parsing.Tree
	path     string
	isTest   bool
	findings []analysis.Finding
}

func (c *checker) report(rule string, n *ts.Node) {
	c.findings = append(c.findings, analysis.Finding{Rule: rule, Path: c.path, Line: parsing.Line(n)})
}

// callee returns a call's receiver (nil for a plain function call) and the
// lowercased name called, since PHP function and method names are case
// insensitive: $db->query() gives ($db, "query"), DB::select() gives (DB,
// "select"), and \exec() gives (nil, "exec"). Dynamic names ($obj->$m())
// give "".
func (c *checker) callee(call *ts.Node) (*ts.Node, string) {
	switch call.Kind() {
	case "function_call_expression":
		fn := call.ChildByFieldName("function")
		if fn == nil || fn.Kind() != "name" && fn.Kind() != "qualified_name" {
			return nil, ""
		}
		name := c.tree.Text(fn)
		return nil, strings.ToLower(name[strings.LastIndex(name, `\`)+1:])
	case "member_call_expression", "nullsafe_member_call_expression":
		if name := call.ChildByFieldName("name"); name != nil && name.Kind() == "name" {
			return call.ChildByFieldName("object"), strings.ToLower(c.tree.Text(name))
		}
	case "scoped_call_expression":
		if name := call.ChildByFieldName("name"); name != nil && name.Kind() == "name" {
			return call.ChildByFieldName("scope"), strings.ToLower(c.tree.Text(name))
		}
	}
	return nil, ""
}

// arguments returns the expressions passed to a call, in order. A named
// argument (sql: "...") ends with its value; spread and first-class callable
// placeholders are left out.
func arguments(call *ts.Node) []*ts.Node {
	args := call.ChildByFieldName("arguments")
	if args == nil {
		// new Foo(...) has an unlabeled arguments child.
		for _, child := range parsing.NamedChildren(call) {
			if child.Kind() == "arguments" {
				args = child
			}
		}
	}
	if args == nil {
		return nil
	}
	var out []*ts.Node
	for _, arg := range parsing.NamedChildren(args) {
		if arg.Kind() == "argument" && arg.NamedChildCount() > 0 {
			out = append(out, arg.NamedChild(arg.NamedChildCount()-1))
		}
	}
	return out
}

// variableName returns the name of a $variable without the $, or "".
func (c *checker) variableName(n *ts.Node) string {
	if n == nil || n.Kind() != "variable_name" {
		return ""
	}
	if name := n.NamedChild(0); name != nil && name.Kind() == "name" {
		return c.tree.Text(name)
	}
	return ""
}

// requestInput are the superglobals that hold what the client sent.
var requestInput = map[string]bool{"_GET": true, "_POST": true, "_COOKIE": true, "_REQUEST": true, "_FILES": true}

// usesRequestInput reports whether an expression reads a request superglobal
// anywhere inside it, such as base64_decode($_COOKIE['cart']).
func (c *checker) usesRequestInput(n *ts.Node) bool {
	found := false
	parsing.Walk(n, func(m *ts.Node) bool {
		if requestInput[c.variableName(m)] {
			found = true
		}
		return !found
	})
	return found
}
