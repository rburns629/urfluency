func findings(t *testing.T, path, src string, positive bool) []string {
	t.Helper()
	got, err := Analyzer{}.Analyze(context.Background(), []analysis.File{{Path: path, Content: []byte(src)}})
	if err != nil {
		t.Fatal(err)
	}
	out := []string{}
	for _, f := range got {
		if f.Positive != positive {
			continue
		}
		if _, ok := rules.Lookup(f.Rule); !ok {
			t.Errorf("%s is not in the catalog", f.Rule)
		}
		out = append(out, fmt.Sprintf("%s:%d", f.Rule, f.Line))
	}
	sort.Strings(out)
	return out
}

func TestRules(t *testing.T) {
	tests := []struct {
		name string
		src  string
		want []string
	}{
		{
			name: "unquoted expansions in commands, not in quotes, assignments, or [[ ]]",
			src: `set -e
cp $src "$dst"
echo "$name" ${#items[@]} $#
x=$y
[[ -n $z ]] && echo ok
ls $(pwd)/dir
`,
			want: []string{"shell.unquoted-expansion:2", "shell.unquoted-expansion:6"},
		},
		{
			name: "a script without set -e, and cd without a check",
			src: `#!/bin/bash
cd /tmp
cd /var || exit 1
`,
			want: []string{"shell.cd-unchecked:2", "shell.missing-errexit:1"},
		},
		{
			name: "set -euo pipefail covers errexit and cd",
			src: `#!/usr/bin/env bash
set -euo pipefail
cd /tmp
`,
			want: []string{},
		},
		{
			name: "a sourced library without a shebang is not a script",
			src: `greet() { echo "hi"; }
`,
			want: []string{},
		},
		{
			name: "eval on expanded input, not on a literal",
			src: `set -e
eval "$cmd"
eval 'echo hi'
`,
			want: []string{"shell.eval:2"},
		},
		{
			name: "download piped into a shell, including sudo",
			src: `set -e
curl -fsSL https://example.com/install.sh | sh
wget -qO- https://example.com/i | sudo bash
curl -s https://example.com/data | jq .
`,
			want: []string{"shell.pipe-to-shell:2", "shell.pipe-to-shell:3"},
		},
		{
			name: "recursive rm of a variable's contents, unless guarded or a subpath",
			src: `set -e
rm -rf "$BUILD/"
rm -r "$TMP"/*
rm -rf "${BUILD:?}/"
rm -rf "$work/.cache"
rm "$FILE/"
`,
			want: []string{"shell.rm-unguarded-path:2", "shell.rm-unguarded-path:3"},
		},
		{
			name: "looping over ls and backticks",
			src: `set -e
for f in $(ls *.txt); do echo "$f"; done
now=` + "`date`" + `
`,
			want: []string{"shell.backtick-substitution:3", "shell.ls-in-loop:2"},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := findings(t, "scripts/a.sh", tt.src, false); !reflect.DeepEqual(got, tt.want) {
				t.Errorf("got %v, want %v", got, tt.want)
			}
		})
	}
}

func TestIdioms(t *testing.T) {
	src := `#!/usr/bin/env bash
set -euo pipefail
trap cleanup EXIT

cleanup() { rm -f "${TMPFILE:-}"; }

main() {
  local name="${1:?usage: greet NAME}"
  while getopts "v" opt; do :; done
  while IFS= read -r line; do echo "$line"; done < file
  if [[ -n "$name" ]]; then printf '%s\n' "${args[@]}"; fi
}

main "$@"
`
	res, err := Analyzer{}.Analyze(context.Background(), []analysis.File{{Path: "a.sh", Content: []byte(src)}})
	if err != nil {
		t.Fatal(err)
	}
	got := map[string]bool{}
	for _, f := range res {
		got[f.Rule] = f.Positive
	}
	for _, r := range rules.ForLanguage("shell") {
		if r.Category == rules.Idiom && !got[r.ID] {
			t.Errorf("%s not found", r.ID)
		}
	}
}

func TestSkip(t *testing.T) {
	a := Analyzer{}
	if !a.Skip(analysis.File{Path: "ios/Flutter/flutter_export_environment.sh"}) {
		t.Error("Flutter's generated script is not skipped")
	}
	if !a.Skip(analysis.File{Path: "gen.sh", Content: []byte("#!/bin/sh\n# Generated by protoc. DO NOT EDIT.\n")}) {
		t.Error("a generated script is not skipped")
	}
	if a.Skip(analysis.File{Path: "deploy.sh", Content: []byte("#!/bin/sh\nset -e\n")}) {
		t.Error("a hand-written script is skipped")
	}
}
