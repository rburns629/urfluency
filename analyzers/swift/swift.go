// Package swift analyzes Swift source with tree-sitter. It parses files and
// never builds or runs them.
package swift

import (
	"bytes"
	"context"
	"path"
	"strings"

	ts "github.com/tree-sitter/go-tree-sitter"

	"github.com/rburns629/urfluency/analysis"
	"github.com/rburns629/urfluency/parsing"
)

func init() { analysis.Register(Analyzer{}) }

// Analyzer implements analysis.Analyzer for Swift.
type Analyzer struct{}

func (Analyzer) Language() string     { return "swift" }
func (Analyzer) Extensions() []string { return []string{".swift"} }

// SkipPath excludes build output and dependency checkouts: SwiftPM's .build,
// Xcode's DerivedData, CocoaPods, and Carthage, plus R.swift's generated file.
func (Analyzer) SkipPath(p string) bool {
	return parsing.InDir(p, ".build", "DerivedData", "Pods", "Carthage") || strings.HasSuffix(path.Base(p), ".generated.swift")
}

// generatedMarkers appear in the headers of generated Swift: SwiftGen and
// Sourcery ("Generated using"), protoc ("DO NOT EDIT"), Apollo ("@generated").
var generatedMarkers = []string{"generated by", "generated using", "do not edit", "@generated", "autogenerated", "auto-generated", "automatically generated"}

// Skip excludes build output, dependencies, and generated files.
func (a Analyzer) Skip(f analysis.File) bool {
	if a.SkipPath(f.Path) {
		return true
	}
	head := bytes.ToLower(f.Content[:min(len(f.Content), 512)])
	for _, m := range generatedMarkers {
		if bytes.Contains(head, []byte(m)) {
			return true
		}
	}
	return false
}

// complexity names Swift nodes for cognitive complexity. An if nested directly
// in an if is an else-if, so ElseClause is if_statement. guard counts once
// through its else. The grammar has two logical-operator kinds and no operator
// field, so logical sequences, labeled jumps, and recursion are not counted.
var complexity = parsing.ComplexitySyntax{
	Functions: map[string]bool{"function_declaration": true, "init_declaration": true, "deinit_declaration": true,
		"subscript_declaration": true, "computed_property": true, "lambda_literal": true},
	Structures: map[string]bool{"if_statement": true, "for_statement": true, "while_statement": true,
		"repeat_while_statement": true, "switch_statement": true, "catch_block": true, "ternary_expression": true},
	Hybrids:      map[string]bool{"else": true},
	ElseClause:   "if_statement",
	LogicalKinds: map[string]string{"conjunction_expression": "&&", "disjunction_expression": "||"},
	LogicalOps:   map[string]bool{"&&": true, "||": true},
}

// Analyze applies every Swift rule and idiom to each file.
func (Analyzer) Analyze(ctx context.Context, files []analysis.File) ([]analysis.Finding, error) {
	var findings []analysis.Finding
	for _, f := range files {
		if err := ctx.Err(); err != nil {
			return nil, err
		}
		tree, err := parsing.Parse(parsing.Swift, f.Content)
		if err != nil {
			continue
		}
		c := checker{tree: tree, path: f.Path, isTest: analysis.IsTestPath(f.Path), protocols: protocolNames(tree)}
		parsing.Walk(tree.Root(), c.visit)
		parsing.Walk(tree.Root(), c.visitIdioms)
		if !c.isTest {
			for _, fn := range parsing.Cognitive(tree, complexity) {
				if fn.Complexity > parsing.CognitiveThreshold {
					c.findings = append(c.findings, analysis.Finding{Rule: "clean.cognitive-complexity", Path: f.Path, Line: fn.Line})
				}
			}
		}
		tree.Close()
		findings = append(findings, c.findings...)
	}
	return findings, nil
}

type checker struct {
	tree      *parsing.Tree
	path      string
	isTest    bool
	protocols map[string]bool // protocols declared in the file
	findings  []analysis.Finding
}

func (c *checker) report(rule string, n *ts.Node) {
	c.findings = append(c.findings, analysis.Finding{Rule: rule, Path: c.path, Line: parsing.Line(n)})
}

// visit applies the rules. Crash operators (!, try!, as!, T!) are common and
// accepted in tests, so those rules apply outside tests only.
func (c *checker) visit(n *ts.Node) bool {
	switch n.Kind() {
	case "postfix_expression":
		if op := n.ChildByFieldName("operation"); !c.isTest && op != nil && op.Kind() == "bang" && !c.literalConstruction(n.ChildByFieldName("target")) {
			c.report("swift.force-unwrap", n)
		}
	case "try_operator":
		if !c.isTest && parsing.HasToken(n, "!") {
			c.report("swift.force-try", n)
		}
	case "as_operator":
		if !c.isTest && parsing.HasToken(n, "as!") {
			c.report("swift.force-cast", n)
		}
	case "type_annotation", "parameter":
		if !c.isTest && parsing.HasToken(n, "!") && !c.outlet(n) {
			c.report("swift.implicitly-unwrapped-optional", n)
		}
	case "catch_block":
		if !hasChild(n, "statements") {
			c.report("swift.empty-catch", n)
		}
	case "call_expression":
		if !c.isTest && c.insecureURL(n) {
			c.report("swift.http-url-literal", n)
		}
	case "equality_expression", "infix_expression", "comparison_expression":
		if c.countComparedWithZero(n) {
			c.report("swift.count-instead-of-is-empty", n)
		}
	}
	return true
}

func hasChild(n *ts.Node, kind string) bool {
	for _, child := range parsing.NamedChildren(n) {
		if child.Kind() == kind {
			return true
		}
	}
	return false
}

// literalConstruction reports whether a node is a call whose arguments are all
// plain string literals, such as URL(string: "https://example.com"). Force
// unwrapping those fails only on a typo that the first run reveals.
func (c *checker) literalConstruction(n *ts.Node) bool {
	if n == nil || n.Kind() != "call_expression" {
		return false
	}
	args := callArguments(n)
	if len(args) == 0 {
		return false
	}
	for _, arg := range args {
		v := arg.ChildByFieldName("value")
		if v == nil || v.Kind() != "line_string_literal" || v.ChildByFieldName("interpolation") != nil {
			return false
		}
	}
	return true
}

// callArguments returns the value_argument nodes of a call's parentheses.
func callArguments(call *ts.Node) []*ts.Node {
	var out []*ts.Node
	for _, suffix := range parsing.NamedChildren(call) {
		if suffix.Kind() != "call_suffix" {
			continue
		}
		for _, args := range parsing.NamedChildren(suffix) {
			if args.Kind() != "value_arguments" {
				continue
			}
			for _, arg := range parsing.NamedChildren(args) {
				if arg.Kind() == "value_argument" {
					out = append(out, arg)
				}
			}
		}
	}
	return out
}

// calleeName returns the plain identifier a call invokes, or "".
func (c *checker) calleeName(call *ts.Node) string {
	if fn := call.NamedChild(0); fn != nil && fn.Kind() == "simple_identifier" {
		return c.tree.Text(fn)
	}
	return ""
}

// outlet reports whether a T! annotation belongs to an @IBOutlet property, which
// Interface Builder sets after init.
func (c *checker) outlet(annotation *ts.Node) bool {
	decl := annotation.Parent()
	if decl == nil || decl.Kind() != "property_declaration" {
		return false
	}
	for _, child := range parsing.NamedChildren(decl) {
		if child.Kind() == "modifiers" && strings.Contains(c.tree.Text(child), "@IBOutlet") {
			return true
		}
	}
	return false
}

// localHosts are development hosts where plain HTTP is expected: loopback, the
// Android emulator's host alias. Names ending in .local (mDNS) are also local.
var localHosts = map[string]bool{"localhost": true, "127.0.0.1": true, "0.0.0.0": true, "[::1]": true, "10.0.2.2": true}

// insecureURL reports URL(string:) or URLComponents(string:) with an http://
// literal for a host other than a local one.
func (c *checker) insecureURL(call *ts.Node) bool {
	if name := c.calleeName(call); name != "URL" && name != "URLComponents" {
		return false
	}
	args := callArguments(call)
	if len(args) == 0 {
		return false
	}
	label := args[0].ChildByFieldName("name")
	value := args[0].ChildByFieldName("value")
	if label == nil || c.tree.Text(label) != "string" || value == nil || value.Kind() != "line_string_literal" {
		return false
	}
	text := value.ChildByFieldName("text")
	if text == nil || text.StartByte() != value.StartByte()+1 {
		return false // the literal does not start with plain text
	}
	rest, ok := strings.CutPrefix(c.tree.Text(text), "http://")
	if !ok {
		return false
	}
	host := rest
	if i := strings.IndexAny(rest, "/?#"); i >= 0 {
		host = rest[:i]
	}
	if i := strings.LastIndex(host, ":"); i >= 0 && !strings.HasSuffix(host, "]") {
		host = host[:i] // strip the port
	}
	// An empty host is built by interpolation, which the literal does not reveal.
	return host != "" && !localHosts[host] && !strings.HasSuffix(host, ".local") && !strings.HasSuffix(host, ".localhost")
}

// countComparedWithZero matches x.count == 0, x.count != 0, x.count > 0, and
// the mirrored forms.
func (c *checker) countComparedWithZero(n *ts.Node) bool {
	lhs, op, rhs := n.ChildByFieldName("lhs"), n.ChildByFieldName("op"), n.ChildByFieldName("rhs")
	if lhs == nil || op == nil || rhs == nil {
		return false
	}
	switch o := c.tree.Text(op); {
	case c.isCount(lhs) && c.isZero(rhs):
		return o == "==" || o == "!=" || o == ">"
	case c.isZero(lhs) && c.isCount(rhs):
		return o == "==" || o == "!=" || o == "<"
	}
	return false
}

func (c *checker) isZero(n *ts.Node) bool {
	return n.Kind() == "integer_literal" && c.tree.Text(n) == "0"
}

// isCount reports whether a node reads a .count property.
func (c *checker) isCount(n *ts.Node) bool {
	if n.Kind() != "navigation_expression" {
		return false
	}
	suffix := n.ChildByFieldName("suffix")
	if suffix == nil {
		return false
	}
	name := suffix.ChildByFieldName("suffix")
	return name != nil && c.tree.Text(name) == "count"
}

// protocolNames returns the names of protocols declared in a file, so that
// extensions of them count as protocol-oriented code.
func protocolNames(t *parsing.Tree) map[string]bool {
	names := map[string]bool{}
	parsing.Walk(t.Root(), func(n *ts.Node) bool {
		if n.Kind() == "protocol_declaration" {
			if name := n.ChildByFieldName("name"); name != nil {
				names[t.Text(name)] = true
			}
			return false
		}
		return true
	})
	return names
}
