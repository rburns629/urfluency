// Package ruby analyzes Ruby source with tree-sitter. It parses files and never
// loads or runs them.
package ruby

import (
	"bytes"
	"context"
	"sort"
	"strings"

	ts "github.com/tree-sitter/go-tree-sitter"

	"github.com/rburns629/urfluency/analysis"
	"github.com/rburns629/urfluency/parsing"
)

func init() { analysis.Register(Analyzer{}) }

// Analyzer implements analysis.Analyzer for Ruby.
type Analyzer struct{}

func (Analyzer) Language() string { return "ruby" }

// Extensions lists Ruby source, Rake task, gem specification, and Rack config
// files. Analyzers are chosen by extension, so Gemfile and Rakefile, which have
// none, are not read.
func (Analyzer) Extensions() []string { return []string{".rb", ".rake", ".gemspec", ".ru"} }

// SkipPath excludes Rails' tmp folder (caches and generated files). Bundler's
// vendor/bundle and .bundle are dependency folders the engine already skips.
func (Analyzer) SkipPath(p string) bool {
	return parsing.InDir(p, "tmp")
}

// generatedMarkers are lowercase header phrases of code generators, including
// Rails' "auto-generated" db/schema.rb.
var generatedMarkers = [][]byte{
	[]byte("do not edit"), []byte("@generated"), []byte("code generated"), []byte("generated by"),
	[]byte("auto-generated"), []byte("automatically generated"), []byte("this file was generated"),
}

// Skip excludes tmp files and files whose header marks them as generated.
func (a Analyzer) Skip(f analysis.File) bool {
	if a.SkipPath(f.Path) {
		return true
	}
	head := f.Content
	if len(head) > 512 {
		head = head[:512]
	}
	head = bytes.ToLower(head)
	for _, m := range generatedMarkers {
		if containsWord(head, m) {
			return true
		}
	}
	return false
}

// containsWord reports whether s contains word not followed by a letter, so
// @generated matches but a longer word such as @generatedvalue does not.
func containsWord(s, word []byte) bool {
	for i := bytes.Index(s, word); i >= 0; {
		end := i + len(word)
		if end == len(s) || s[end] < 'a' || s[end] > 'z' {
			return true
		}
		next := bytes.Index(s[end:], word)
		if next < 0 {
			return false
		}
		i = end + next
	}
	return false
}

// complexity names this grammar's nodes for cognitive complexity. Blocks
// (do...end and {...}) are functions that nest, as lambdas are in other
// languages; a lambda's body is such a block, so lambda itself is not listed
// or it would nest twice. Statement modifiers (x if y, x while y) count like
// their full forms, and rescue counts like catch. elsif is its own node inside
// the if, so it adds 1 without nesting and no else-if correction is needed.
// The grammar uses one else node for if, unless, case, and begin, so the else
// of a case also adds 1, overcounting such a case by one. Ruby has no labeled
// jumps, and call has no function field, so recursion is not counted.
var complexity = parsing.ComplexitySyntax{
	Functions: set("method", "singleton_method", "block", "do_block"),
	Structures: set("if", "unless", "if_modifier", "unless_modifier", "while", "until", "while_modifier",
		"until_modifier", "for", "case", "case_match", "conditional", "rescue", "rescue_modifier"),
	Hybrids:    set("elsif", "else"),
	Logical:    "binary",
	LogicalOps: set("&&", "||", "and", "or"),
}

func set(kinds ...string) map[string]bool {
	m := make(map[string]bool, len(kinds))
	for _, k := range kinds {
		m[k] = true
	}
	return m
}

// Analyze applies every Ruby rule and idiom to each file.
func (Analyzer) Analyze(ctx context.Context, files []analysis.File) ([]analysis.Finding, error) {
	var findings []analysis.Finding
	for _, f := range files {
		if err := ctx.Err(); err != nil {
			return nil, err
		}
		tree, err := parsing.Parse(parsing.Ruby, f.Content)
		if err != nil {
			continue
		}
		c := checker{tree: tree, path: f.Path, isTest: analysis.IsTestPath(f.Path), heredocs: heredocBodies(tree)}
		parsing.Walk(tree.Root(), c.visit)
		parsing.Walk(tree.Root(), c.visitIdioms)
		if !c.isTest {
			for _, fn := range parsing.Cognitive(tree, complexity) {
				if fn.Complexity > parsing.CognitiveThreshold {
					c.findings = append(c.findings, analysis.Finding{Rule: "clean.cognitive-complexity", Path: f.Path, Line: fn.Line})
				}
			}
		}
		tree.Close()
		findings = append(findings, c.findings...)
	}
	return findings, nil
}

// frameworkRequires map the first segment of a required library to frameworks.
// require_relative loads the project's own files, so it names no framework.
// rails_helper and spec_helper are RSpec's conventional setup files.
var frameworkRequires = map[string][]string{
	"rails": {"rails"}, "active_record": {"rails"}, "action_controller": {"rails"}, "action_view": {"rails"},
	"action_mailer": {"rails"}, "action_cable": {"rails"}, "active_job": {"rails"}, "active_storage": {"rails"},
	"sinatra": {"sinatra"}, "hanami": {"hanami"}, "roda": {"roda"}, "grape": {"grape"},
	"rspec": {"rspec"}, "spec_helper": {"rspec"}, "rails_helper": {"rspec", "rails"},
	"minitest": {"minitest"}, "sidekiq": {"sidekiq"}, "sequel": {"sequel"},
}

// frameworkConstants map the top-level constant of a referenced name, such as
// ActiveRecord in ActiveRecord::Base, to frameworks. The Application* classes
// are the base classes every Rails app generates.
var frameworkConstants = map[string][]string{
	"Rails": {"rails"}, "ActiveRecord": {"rails"}, "ActionController": {"rails"}, "ActionDispatch": {"rails"},
	"ActionMailer": {"rails"}, "ActionCable": {"rails"}, "ActiveJob": {"rails"}, "ActiveStorage": {"rails"},
	"ApplicationRecord": {"rails"}, "ApplicationController": {"rails"}, "ApplicationJob": {"rails"}, "ApplicationMailer": {"rails"},
	"Sinatra": {"sinatra"}, "Hanami": {"hanami"}, "Roda": {"roda"}, "Grape": {"grape"},
	"RSpec": {"rspec"}, "Minitest": {"minitest"}, "Sidekiq": {"sidekiq"}, "Sequel": {"sequel"},
}

// Frameworks implements analysis.FrameworkDetector from a file's require calls
// and the framework constants it references.
func (Analyzer) Frameworks(f analysis.File) []string {
	tree, err := parsing.Parse(parsing.Ruby, f.Content)
	if err != nil {
		return nil
	}
	defer tree.Close()
	found := map[string]bool{}
	parsing.Walk(tree.Root(), func(n *ts.Node) bool {
		var fws []string
		switch n.Kind() {
		case "call":
			if lib := requiredLibrary(tree, n); lib != "" {
				fws = frameworkRequires[strings.SplitN(lib, "/", 2)[0]]
			}
		case "constant":
			if !definedOrNested(n) {
				fws = frameworkConstants[tree.Text(n)]
			}
		}
		for _, fw := range fws {
			found[fw] = true
		}
		return true
	})
	out := make([]string, 0, len(found))
	for fw := range found {
		out = append(out, fw)
	}
	sort.Strings(out)
	return out
}

// requiredLibrary returns the literal path of require "lib", or "".
func requiredLibrary(t *parsing.Tree, call *ts.Node) string {
	if call.ChildByFieldName("receiver") != nil || calleeName(t, call) != "require" {
		return ""
	}
	args := arguments(call)
	if len(args) != 1 || args[0].Kind() != "string" || args[0].NamedChildCount() != 1 {
		return ""
	}
	if part := args[0].NamedChild(0); part.Kind() == "string_content" {
		return t.Text(part)
	}
	return ""
}

// definedOrNested reports whether a constant is the name of a class or module
// being defined, or the inner part of a scoped name (the Rails of Foo::Rails),
// neither of which refers to a framework.
func definedOrNested(n *ts.Node) bool {
	parent := n.Parent()
	if parent == nil {
		return false
	}
	switch parent.Kind() {
	case "class", "module":
		return isField(parent, "name", n)
	case "scope_resolution":
		return isField(parent, "name", n)
	}
	return false
}

// isField reports whether n is the given field of parent.
func isField(parent *ts.Node, field string, n *ts.Node) bool {
	f := parent.ChildByFieldName(field)
	return f != nil && f.Id() == n.Id()
}

type checker struct {
	tree     *parsing.Tree
	path     string
	isTest   bool
	heredocs map[uint]*ts.Node // heredoc_beginning start byte to its body
	findings []analysis.Finding
}

func (c *checker) report(rule string, n *ts.Node) {
	c.findings = append(c.findings, analysis.Finding{Rule: rule, Path: c.path, Line: parsing.Line(n)})
}

// heredocBodies pairs each heredoc opener (<<~SQL) with its body. The grammar
// places bodies after the statement, in the order the openers appear.
func heredocBodies(t *parsing.Tree) map[uint]*ts.Node {
	var openers, bodies []*ts.Node
	parsing.Walk(t.Root(), func(n *ts.Node) bool {
		switch n.Kind() {
		case "heredoc_beginning":
			openers = append(openers, n)
		case "heredoc_body":
			bodies = append(bodies, n)
		}
		return true
	})
	out := make(map[uint]*ts.Node, len(openers))
	for i, o := range openers {
		if i < len(bodies) {
			out[o.StartByte()] = bodies[i]
		}
	}
	return out
}

// callee returns a call's receiver (nil for a plain call) and the name of the
// method called: x.f() gives (x, "f"), f() gives (nil, "f").
func (c *checker) callee(call *ts.Node) (*ts.Node, string) {
	return call.ChildByFieldName("receiver"), calleeName(c.tree, call)
}

func calleeName(t *parsing.Tree, call *ts.Node) string {
	if m := call.ChildByFieldName("method"); m != nil {
		return t.Text(m)
	}
	return ""
}

// arguments returns the expressions passed to a call, with or without
// parentheses.
func arguments(call *ts.Node) []*ts.Node {
	args := call.ChildByFieldName("arguments")
	if args == nil {
		return nil
	}
	return parsing.NamedChildren(args)
}

// hasBlock reports whether a call takes a block: { ... }, do ... end, or &:name.
func hasBlock(call *ts.Node) bool {
	if call.ChildByFieldName("block") != nil {
		return true
	}
	for _, arg := range arguments(call) {
		if arg.Kind() == "block_argument" {
			return true
		}
	}
	return false
}

// receiverIs reports whether a call's receiver is one of the named constants,
// optionally written from the top level (::YAML).
func (c *checker) receiverIs(receiver *ts.Node, names ...string) bool {
	if receiver == nil {
		return false
	}
	text := strings.TrimPrefix(c.tree.Text(receiver), "::")
	for _, name := range names {
		if text == name {
			return true
		}
	}
	return false
}
