// Package cpp analyzes C++ source with tree-sitter. It parses files and never
// compiles, preprocesses, or runs them or their build tooling.
package cpp

import (
	"bytes"
	"context"
	"path"
	"strings"

	ts "github.com/tree-sitter/go-tree-sitter"

	"github.com/rburns629/urfluency/analysis"
	"github.com/rburns629/urfluency/parsing"
)

func init() { analysis.Register(Analyzer{}) }

// Analyzer implements analysis.Analyzer for C++. Headers ending in .h belong to
// the C analyzer.
type Analyzer struct{}

func (Analyzer) Language() string { return "cpp" }
func (Analyzer) Extensions() []string {
	return []string{".cc", ".cpp", ".cxx", ".c++", ".hh", ".hpp", ".hxx"}
}

// SkipPath excludes build output directories, such as build/, out/,
// cmake-build-debug/, and bazel-bin/.
func (Analyzer) SkipPath(p string) bool {
	parts := strings.Split(p, "/")
	for _, dir := range parts[:len(parts)-1] {
		if dir == "build" || dir == "out" || strings.HasPrefix(dir, "cmake-build-") || strings.HasPrefix(dir, "bazel-") {
			return true
		}
	}
	return false
}

// generatedMarkers appear, lower-cased, near the top of generated sources such
// as Qt moc output and protobuf or gRPC stubs.
var generatedMarkers = [][]byte{[]byte("generated by"), []byte("automatically generated"), []byte("do not edit"), []byte("@generated")}

// Skip excludes build output and generated files: Qt moc and rcc output,
// protobuf and gRPC stubs, and files whose header says they are generated.
func (a Analyzer) Skip(f analysis.File) bool {
	if a.SkipPath(f.Path) {
		return true
	}
	base := path.Base(f.Path)
	if strings.HasPrefix(base, "moc_") || strings.HasPrefix(base, "qrc_") ||
		strings.Contains(base, ".pb.") {
		return true
	}
	head := bytes.ToLower(f.Content[:min(len(f.Content), 1024)])
	for _, m := range generatedMarkers {
		if bytes.Contains(head, m) {
			return true
		}
	}
	return false
}

// Complexity is the C++ syntax for cognitive complexity. Function definitions
// have no name field, so recursion is not counted.
var Complexity = parsing.ComplexitySyntax{
	Functions: map[string]bool{"function_definition": true, "lambda_expression": true},
	Structures: map[string]bool{"if_statement": true, "for_statement": true, "for_range_loop": true, "while_statement": true,
		"do_statement": true, "switch_statement": true, "catch_clause": true, "conditional_expression": true},
	Hybrids:    map[string]bool{"else_clause": true},
	ElseClause: "else_clause",
	Logical:    "binary_expression",
	LogicalOps: map[string]bool{"&&": true, "||": true, "and": true, "or": true},
	// A goto always has a label, so each one adds 1, as the specification asks.
	Jumps: map[string]bool{"goto_statement": true},
	Label: "statement_identifier",
	Call:  "call_expression",
}

// Analyze applies every C++ rule to each file.
func (Analyzer) Analyze(ctx context.Context, files []analysis.File) ([]analysis.Finding, error) {
	var findings []analysis.Finding
	for _, f := range files {
		if err := ctx.Err(); err != nil {
			return nil, err
		}
		tree, err := parsing.Parse(parsing.CPP, f.Content)
		if err != nil {
			continue
		}
		c := checker{tree: tree, path: f.Path, header: isHeader(f.Path), qt: includedFrameworks(tree)["qt"]}
		parsing.Walk(tree.Root(), c.visit)
		c.checkOverrides()
		parsing.Walk(tree.Root(), c.visitIdioms)
		if !analysis.IsTestPath(f.Path) {
			for _, fn := range parsing.Cognitive(tree, Complexity) {
				if fn.Complexity > parsing.CognitiveThreshold {
					c.findings = append(c.findings, analysis.Finding{Rule: "clean.cognitive-complexity", Path: f.Path, Line: fn.Line})
				}
			}
		}
		tree.Close()
		findings = append(findings, c.findings...)
	}
	return findings, nil
}

func isHeader(p string) bool {
	switch strings.ToLower(path.Ext(p)) {
	case ".h", ".hh", ".hpp", ".hxx":
		return true
	}
	return false
}

type checker struct {
	tree     *parsing.Tree
	path     string
	header   bool
	qt       bool // Qt objects are commonly created with new and owned by their parent
	classes  []*ts.Node
	findings []analysis.Finding
}

func (c *checker) report(rule string, n *ts.Node) {
	c.findings = append(c.findings, analysis.Finding{Rule: rule, Path: c.path, Line: parsing.Line(n)})
}

func (c *checker) visit(n *ts.Node) bool {
	switch n.Kind() {
	case "new_expression":
		if !c.qt && n.ChildByFieldName("placement") == nil && !c.ownedBySmartPointer(n) {
			c.report("cpp.raw-new-delete", n)
		}
	case "delete_expression":
		c.report("cpp.raw-new-delete", n)
	case "cast_expression":
		// (void)x discards a value on purpose; it is not a conversion.
		if typ := n.ChildByFieldName("type"); typ != nil && c.tree.Text(typ) != "void" {
			c.report("cpp.c-style-cast", n)
		}
	case "using_declaration":
		if c.header && parsing.HasToken(n, "namespace") && !inside(n, "function_definition") {
			c.report("cpp.using-namespace-in-header", n)
		}
	case "call_expression":
		c.checkCall(n)
	case "catch_clause":
		c.checkCatch(n)
	case "class_specifier", "struct_specifier":
		if n.ChildByFieldName("body") != nil {
			c.classes = append(c.classes, n)
		}
	}
	return true
}

// smartPointers are the types and resetters that take ownership of a new pointer.
var smartPointers = []string{"unique_ptr", "shared_ptr", "scoped_ptr", "QScopedPointer", "QSharedPointer"}

func isSmartPointer(text string) bool {
	for _, s := range smartPointers {
		if strings.Contains(text, s) {
			return true
		}
	}
	return false
}

// ownedBySmartPointer reports whether a new expression is handed straight to a
// smart pointer: std::unique_ptr<T> p(new T), p{new T}, unique_ptr<T>(new T), or
// p.reset(new T).
func (c *checker) ownedBySmartPointer(n *ts.Node) bool {
	args := n.Parent()
	if args == nil || (args.Kind() != "argument_list" && args.Kind() != "initializer_list") {
		return false
	}
	owner := args.Parent()
	if owner == nil {
		return false
	}
	switch owner.Kind() {
	case "call_expression":
		fn := owner.ChildByFieldName("function")
		if fn == nil {
			return false
		}
		if fn.Kind() == "field_expression" {
			field := fn.ChildByFieldName("field")
			return field != nil && c.tree.Text(field) == "reset"
		}
		return isSmartPointer(c.tree.Text(fn))
	case "init_declarator":
		if decl := owner.Parent(); decl != nil {
			typ := decl.ChildByFieldName("type")
			return typ != nil && isSmartPointer(c.tree.Text(typ))
		}
	case "compound_literal_expression":
		typ := owner.ChildByFieldName("type")
		return typ != nil && isSmartPointer(c.tree.Text(typ))
	}
	return false
}

// inside reports whether a node has an ancestor of the given kind.
func inside(n *ts.Node, kind string) bool {
	for p := n.Parent(); p != nil; p = p.Parent() {
		if p.Kind() == kind {
			return true
		}
	}
	return false
}

var unsafeStringFunctions = map[string]bool{"strcpy": true, "strcat": true, "sprintf": true, "vsprintf": true, "gets": true}

var stringLiteralKinds = map[string]bool{"string_literal": true, "raw_string_literal": true, "concatenated_string": true}

// calleeName returns the unqualified name of a free-function call, such as
// strcpy for std::strcpy or ::strcpy, and "" for member calls.
func (c *checker) calleeName(call *ts.Node) string {
	fn := call.ChildByFieldName("function")
	if fn == nil {
		return ""
	}
	switch fn.Kind() {
	case "identifier":
		return c.tree.Text(fn)
	case "qualified_identifier":
		scope := fn.ChildByFieldName("scope")
		name := fn.ChildByFieldName("name")
		if name != nil && name.Kind() == "identifier" && (scope == nil || c.tree.Text(scope) == "std") {
			return c.tree.Text(name)
		}
	}
	return ""
}

func (c *checker) checkCall(call *ts.Node) {
	name := c.calleeName(call)
	switch {
	case unsafeStringFunctions[name]:
		c.report("cpp.unsafe-c-string", call)
	case name == "system" || name == "popen":
		args := call.ChildByFieldName("arguments")
		if args == nil || args.NamedChildCount() == 0 {
			return
		}
		if !stringLiteralKinds[args.NamedChild(0).Kind()] {
			c.report("cpp.system-call", call)
		}
	}
}

// classTypes are the type nodes that name a class rather than a built-in type.
var classTypes = map[string]bool{"type_identifier": true, "qualified_identifier": true, "template_type": true}

// checkCatch flags empty handlers and class types caught by value.
func (c *checker) checkCatch(clause *ts.Node) {
	if body := clause.ChildByFieldName("body"); body != nil && body.NamedChildCount() == 0 {
		c.report("cpp.empty-catch", clause)
	}
	params := clause.ChildByFieldName("parameters")
	if params == nil || params.NamedChildCount() == 0 {
		return // catch (...)
	}
	p := params.NamedChild(0)
	typ := p.ChildByFieldName("type")
	if p.Kind() != "parameter_declaration" || typ == nil || !classTypes[typ.Kind()] {
		return
	}
	if d := p.ChildByFieldName("declarator"); d == nil || d.Kind() == "identifier" {
		c.report("cpp.catch-by-value", clause)
	}
}
