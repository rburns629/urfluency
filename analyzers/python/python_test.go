package python

import (
	"context"
	"fmt"
	"reflect"
	"sort"
	"testing"

	"github.com/rburns629/urfluency/analysis"
)

func findings(t *testing.T, path, src string) []string {
	t.Helper()
	got, err := Analyzer{}.Analyze(context.Background(), []analysis.File{{Path: path, Content: []byte(src)}})
	if err != nil {
		t.Fatal(err)
	}
	out := []string{}
	for _, f := range got {
		out = append(out, fmt.Sprintf("%s:%d", f.Rule, f.Line))
	}
	sort.Strings(out)
	return out
}

func TestRules(t *testing.T) {
	tests := []struct {
		name string
		path string
		src  string
		want []string
	}{
		{
			name: "mutable defaults",
			path: "app/a.py",
			src: `def f(a: int, b: list = [], c: dict = dict(), *, d: set = {1}) -> None:
    pass
def g(a: int = 0, b: str = "x", c: None = None) -> None:
    pass
`,
			want: []string{"py.mutable-default-argument:1", "py.mutable-default-argument:1", "py.mutable-default-argument:1"},
		},
		{
			name: "bare and swallowed exceptions",
			path: "app/a.py",
			src: `def f() -> None:
    try:
        run()
    except:
        pass
    try:
        run()
    except Exception as e:
        ...
    try:
        run()
    except KeyError:
        pass
    try:
        run()
    except Exception:
        log(e)
`,
			want: []string{"py.bare-except:4", "py.swallowed-exception:4", "py.swallowed-exception:8"},
		},
		{
			name: "identity comparisons with literals but not None",
			path: "app/a.py",
			src: `def f(a: int) -> bool:
    return a is 1 or a is not "x" or a is None or a is True
`,
			want: []string{"py.is-literal-comparison:2", "py.is-literal-comparison:2"},
		},
		{
			name: "open outside with, but not inside with or returned",
			path: "app/a.py",
			src: `def f(p: str) -> str:
    h = open(p)
    with open(p) as g:
        pass
    return open(p)
`,
			want: []string{"py.open-without-with:2"},
		},
		{
			name: "type ignore and unannotated public functions",
			path: "app/a.py",
			src: `x = y  # type: ignore
def public(a, b: int):
    pass
class C:
    def method(self, a: int) -> int:
        return a
    def untyped(self, a):
        return a
    def _private(self, a):
        def inner(b):
            return b
        return a
`,
			want: []string{"py.type-ignore:1", "py.unannotated-public-function:2", "py.unannotated-public-function:7"},
		},
		{
			name: "test files skip the annotation rule",
			path: "tests/test_a.py",
			src: `def test_something(client):
    assert client
`,
			want: []string{},
		},
		{
			name: "test methods and hooks skip the annotation rule anywhere",
			path: "app/payment_tests.py",
			src: `class Contract:
    def setUp(self):
        pass
    def test_valid(self):
        pass
`,
			want: []string{},
		},
		{
			name: "test-named methods in ordinary files are still skipped",
			path: "app/checks.py",
			src: `class Contract:
    def test_valid(self):
        pass
    def helper(self, x):
        return x
`,
			want: []string{"py.unannotated-public-function:4"},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := findings(t, tt.path, tt.src); !reflect.DeepEqual(got, tt.want) {
				t.Errorf("got %v, want %v", got, tt.want)
			}
		})
	}
}

func TestSkip(t *testing.T) {
	cases := map[string]bool{
		".venv/lib/x.py":   true,
		"app/models.py":    false,
		"app/migrations/1": true,
	}
	for p, want := range cases {
		content := []byte("x = 1\n")
		if p == "app/migrations/1" {
			content = []byte("# Generated by Django 5.0 on 2026-01-01\n")
		}
		if got := (Analyzer{}).Skip(analysis.File{Path: p, Content: content}); got != want {
			t.Errorf("Skip(%s) = %v, want %v", p, got, want)
		}
	}
}
