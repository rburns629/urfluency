// Package clang analyzes C source with tree-sitter. It parses files and never
// compiles, preprocesses, or runs them. The package is not named c to avoid
// confusion with cgo's "C" pseudo-package.
package clang

import (
	"bytes"
	"context"
	"path"
	"sort"
	"strings"

	ts "github.com/tree-sitter/go-tree-sitter"

	"github.com/rburns629/urfluency/analysis"
	"github.com/rburns629/urfluency/parsing"
)

func init() { analysis.Register(Analyzer{}) }

// Analyzer implements analysis.Analyzer for C.
type Analyzer struct{}

func (Analyzer) Language() string     { return "c" }
func (Analyzer) Extensions() []string { return []string{".c", ".h"} }

// SkipPath excludes build output by path alone.
func (Analyzer) SkipPath(p string) bool {
	if parsing.InDir(p, "build", "out") {
		return true
	}
	parts := strings.Split(p, "/")
	for _, dir := range parts[:len(parts)-1] {
		if strings.HasPrefix(dir, "cmake-build-") {
			return true
		}
	}
	return false
}

// Skip excludes build output, generated files, and .h headers that are C++.
func (a Analyzer) Skip(f analysis.File) bool {
	if a.SkipPath(f.Path) || generated(f.Content) {
		return true
	}
	return strings.EqualFold(path.Ext(f.Path), ".h") && isCPP(f.Content)
}

func generated(content []byte) bool {
	head := content
	if len(head) > 512 {
		head = head[:512]
	}
	lower := bytes.ToLower(head)
	return bytes.Contains(lower, []byte("generated by")) || bytes.Contains(head, []byte("DO NOT EDIT")) ||
		bytes.Contains(head, []byte("@generated"))
}

// cppLinePrefixes start lines that only C++ allows; they are matched at the
// start of a line so prose in comments does not count.
var cppLinePrefixes = []string{"class ", "namespace ", "template<", "template <"}

// isCPP reports whether a header contains C++-only syntax.
func isCPP(content []byte) bool {
	for _, line := range strings.Split(string(content), "\n") {
		line = strings.TrimSpace(line)
		if strings.Contains(line, "std::") || strings.Contains(line, `extern "C++"`) {
			return true
		}
		for _, p := range cppLinePrefixes {
			if strings.HasPrefix(line, p) {
				return true
			}
		}
	}
	return false
}

// Complexity names the C grammar's nodes for cognitive complexity. Every goto
// counts, as in SonarSource's specification.
var Complexity = parsing.ComplexitySyntax{
	Functions: kinds("function_definition"),
	Structures: kinds("if_statement", "for_statement", "while_statement", "do_statement",
		"switch_statement", "conditional_expression"),
	Hybrids:    kinds("else_clause"),
	ElseClause: "else_clause",
	Logical:    "binary_expression",
	LogicalOps: kinds("&&", "||"),
	Jumps:      kinds("goto_statement"),
	Label:      "statement_identifier",
	Call:       "call_expression",
}

func kinds(ks ...string) map[string]bool {
	m := make(map[string]bool, len(ks))
	for _, k := range ks {
		m[k] = true
	}
	return m
}

// Analyze applies every C rule and idiom to each file.
func (Analyzer) Analyze(ctx context.Context, files []analysis.File) ([]analysis.Finding, error) {
	var findings []analysis.Finding
	for _, f := range files {
		if err := ctx.Err(); err != nil {
			return nil, err
		}
		tree, err := parsing.Parse(parsing.C, f.Content)
		if err != nil {
			continue
		}
		c := checker{tree: tree, path: f.Path}
		parsing.Walk(tree.Root(), c.visit)
		parsing.Walk(tree.Root(), c.visitIdioms)
		if strings.EqualFold(path.Ext(f.Path), ".h") && c.hasIncludeGuard() {
			c.idiom("c.idiom.include-guard", tree.Root())
		}
		if !analysis.IsTestPath(f.Path) {
			for _, fn := range parsing.Cognitive(tree, Complexity) {
				if fn.Complexity > parsing.CognitiveThreshold {
					c.findings = append(c.findings, analysis.Finding{Rule: "clean.cognitive-complexity", Path: f.Path, Line: fn.Line})
				}
			}
		}
		tree.Close()
		findings = append(findings, c.findings...)
	}
	return findings, nil
}

// Frameworks returns the libraries a file includes, sorted.
func (Analyzer) Frameworks(f analysis.File) []string {
	tree, err := parsing.Parse(parsing.C, f.Content)
	if err != nil {
		return nil
	}
	defer tree.Close()
	found := map[string]bool{}
	parsing.Walk(tree.Root(), func(n *ts.Node) bool {
		if n.Kind() != "preproc_include" {
			return true
		}
		if p := n.ChildByFieldName("path"); p != nil {
			if fw := frameworkOf(strings.Trim(tree.Text(p), `<>"`)); fw != "" {
				found[fw] = true
			}
		}
		return false
	})
	out := make([]string, 0, len(found))
	for fw := range found {
		out = append(out, fw)
	}
	sort.Strings(out)
	return out
}

func frameworkOf(include string) string {
	has := func(prefixes ...string) bool {
		for _, p := range prefixes {
			if strings.HasPrefix(include, p) {
				return true
			}
		}
		return false
	}
	switch {
	case has("gtk/"):
		return "gtk"
	case include == "glib.h" || include == "glib-object.h" || has("glib/", "gio/"):
		return "glib"
	case include == "SDL.h" || has("SDL2/", "SDL3/", "SDL/"):
		return "sdl"
	case has("openssl/"):
		return "openssl"
	case has("curl/"):
		return "libcurl"
	case include == "sqlite3.h":
		return "sqlite3"
	case include == "FreeRTOS.h" || has("freertos/"):
		return "freertos"
	case has("zephyr/"):
		return "zephyr"
	}
	return ""
}

type checker struct {
	tree     *parsing.Tree
	path     string
	findings []analysis.Finding
}

func (c *checker) report(rule string, n *ts.Node) {
	c.findings = append(c.findings, analysis.Finding{Rule: rule, Path: c.path, Line: parsing.Line(n)})
}

// unsafeStringFunctions cannot bound their writes to the destination buffer.
var unsafeStringFunctions = map[string]bool{"gets": true, "strcpy": true, "strcat": true, "sprintf": true, "vsprintf": true}

// formatIndex is the position of the format argument of printf-style functions.
// The v* variants are left out: they usually forward a wrapper's own format.
var formatIndex = map[string]int{"printf": 0, "fprintf": 1, "dprintf": 1, "sprintf": 1, "snprintf": 2, "asprintf": 1, "syslog": 1}

// translators return a translated copy of a literal format, such as _("...").
var translators = map[string]bool{"_": true, "gettext": true, "dgettext": true, "N_": true}

func (c *checker) visit(n *ts.Node) bool {
	switch n.Kind() {
	case "call_expression":
		c.checkCall(n)
	case "assignment_expression":
		c.checkReallocSelfAssign(n)
	case "if_statement", "while_statement", "do_statement":
		if cond := n.ChildByFieldName("condition"); cond != nil && cond.Kind() == "parenthesized_expression" && cond.NamedChildCount() == 1 {
			if inner := cond.NamedChild(0); inner.Kind() == "assignment_expression" && parsing.HasToken(inner, "=") {
				c.report("c.assignment-in-condition", inner)
			}
		}
	case "declaration":
		c.checkEmptyParameterList(n)
	case "function_definition":
		c.checkVoidPointerArithmetic(n)
	}
	return true
}

// callee returns the name of a call to a plain identifier, or "".
func (c *checker) callee(call *ts.Node) string {
	if fn := call.ChildByFieldName("function"); fn != nil && fn.Kind() == "identifier" {
		return c.tree.Text(fn)
	}
	return ""
}

func arguments(call *ts.Node) []*ts.Node {
	if args := call.ChildByFieldName("arguments"); args != nil {
		var out []*ts.Node
		for _, a := range parsing.NamedChildren(args) {
			if a.Kind() != "comment" {
				out = append(out, a)
			}
		}
		return out
	}
	return nil
}

// constantString reports whether an argument is a string literal, a
// concatenation such as "%" PRIu64, a translated literal, or an upper-case
// identifier, which by convention is a macro constant.
func (c *checker) constantString(n *ts.Node) bool {
	switch n.Kind() {
	case "string_literal", "concatenated_string":
		return true
	case "identifier":
		name := c.tree.Text(n)
		return name == strings.ToUpper(name)
	case "call_expression":
		args := arguments(n)
		return translators[c.callee(n)] && len(args) > 0 && c.constantString(args[0])
	}
	return false
}

func (c *checker) checkCall(call *ts.Node) {
	name := c.callee(call)
	args := arguments(call)
	switch {
	case unsafeStringFunctions[name]:
		// Copying a literal is bounded by the literal and easy to verify.
		if (name == "strcpy" || name == "strcat") && len(args) == 2 && args[1].Kind() == "string_literal" {
			return
		}
		c.report("c.unsafe-string-function", call)
	case name == "system" || name == "popen":
		if len(args) > 0 && !c.constantString(args[0]) {
			c.report("c.system-call", call)
		}
	}
	// Only a non-constant format with no further arguments is reported: the
	// classic printf(input) bug, not wrappers that choose among formats.
	if i, ok := formatIndex[name]; ok && len(args) == i+1 && !c.constantString(args[i]) {
		c.report("c.format-string-not-literal", call)
	}
}

func unwrap(n *ts.Node) *ts.Node {
	for n != nil {
		switch n.Kind() {
		case "parenthesized_expression":
			n = n.NamedChild(0)
		case "cast_expression":
			n = n.ChildByFieldName("value")
		default:
			return n
		}
	}
	return n
}

// checkReallocSelfAssign flags p = realloc(p, n), which leaks p when realloc
// fails and returns NULL.
func (c *checker) checkReallocSelfAssign(n *ts.Node) {
	if !parsing.HasToken(n, "=") {
		return
	}
	left, right := n.ChildByFieldName("left"), unwrap(n.ChildByFieldName("right"))
	if left == nil || right == nil || right.Kind() != "call_expression" || c.callee(right) != "realloc" {
		return
	}
	if args := arguments(right); len(args) > 0 && c.tree.Text(unwrap(args[0])) == c.tree.Text(left) {
		c.report("c.realloc-self-assign", n)
	}
}

// checkEmptyParameterList flags prototypes such as int f(); which, before C23,
// declare a function with unchecked arguments rather than none.
func (c *checker) checkEmptyParameterList(decl *ts.Node) {
	for _, d := range parsing.NamedChildren(decl) {
		if d.Kind() != "function_declarator" {
			continue
		}
		name, params := d.ChildByFieldName("declarator"), d.ChildByFieldName("parameters")
		if name == nil || params == nil || name.Kind() != "identifier" {
			continue
		}
		if strings.Join(strings.Fields(c.tree.Text(params)), "") == "()" {
			c.report("c.empty-parameter-list", d)
		}
	}
}

// voidPointerName returns the identifier of a single-level pointer declarator,
// such as *p, or "" for anything else, such as **p or a function pointer.
func (c *checker) voidPointerName(d *ts.Node) string {
	if d.Kind() == "init_declarator" {
		d = d.ChildByFieldName("declarator")
	}
	if d == nil || d.Kind() != "pointer_declarator" {
		return ""
	}
	if id := d.ChildByFieldName("declarator"); id != nil && id.Kind() == "identifier" {
		return c.tree.Text(id)
	}
	return ""
}

func declaredName(t *parsing.Tree, d *ts.Node) string {
	for d != nil && d.Kind() != "identifier" {
		d = d.ChildByFieldName("declarator")
	}
	if d == nil {
		return ""
	}
	return t.Text(d)
}

// checkVoidPointerArithmetic flags ++, --, +=, -=, + and - on parameters and
// locals declared void *. ISO C has no size for void, so this only compiles as
// a GNU extension. Names also declared with another type in the function are
// ignored rather than guessing which declaration is in scope.
func (c *checker) checkVoidPointerArithmetic(fn *ts.Node) {
	voids, others := map[string]bool{}, map[string]bool{}
	parsing.Walk(fn, func(n *ts.Node) bool {
		if n.Kind() != "parameter_declaration" && n.Kind() != "declaration" {
			return true
		}
		typ := n.ChildByFieldName("type")
		isVoid := typ != nil && typ.Kind() == "primitive_type" && c.tree.Text(typ) == "void"
		// Type and qualifier children have no declarator, so they yield no name.
		for _, d := range parsing.NamedChildren(n) {
			if name := c.voidPointerName(d); isVoid && name != "" {
				voids[name] = true
			} else if name := declaredName(c.tree, d); name != "" {
				others[name] = true
			}
		}
		return true
	})
	isVoid := func(n *ts.Node) bool {
		return n != nil && n.Kind() == "identifier" && voids[c.tree.Text(n)] && !others[c.tree.Text(n)]
	}
	if len(voids) == 0 {
		return
	}
	body := fn.ChildByFieldName("body")
	parsing.Walk(body, func(n *ts.Node) bool {
		switch n.Kind() {
		case "update_expression":
			if isVoid(n.ChildByFieldName("argument")) {
				c.report("c.void-pointer-arithmetic", n)
			}
		case "assignment_expression":
			if parsing.HasToken(n, "+=", "-=") && isVoid(n.ChildByFieldName("left")) {
				c.report("c.void-pointer-arithmetic", n)
			}
		case "binary_expression":
			if op := n.ChildByFieldName("operator"); op != nil && (op.Kind() == "+" || op.Kind() == "-") &&
				(isVoid(n.ChildByFieldName("left")) || isVoid(n.ChildByFieldName("right"))) {
				c.report("c.void-pointer-arithmetic", n)
			}
		}
		return true
	})
}
