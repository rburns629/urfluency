// Package kotlin analyzes Kotlin source with tree-sitter. It parses files and
// never compiles or runs them.
package kotlin

import (
	"bytes"
	"context"
	"path"
	"sort"
	"strings"

	ts "github.com/tree-sitter/go-tree-sitter"

	"github.com/rburns629/urfluency/analysis"
	"github.com/rburns629/urfluency/parsing"
)

func init() { analysis.Register(Analyzer{}) }

// Analyzer implements analysis.Analyzer for Kotlin.
type Analyzer struct{}

func (Analyzer) Language() string     { return "kotlin" }
func (Analyzer) Extensions() []string { return []string{".kt", ".kts"} }

// SkipPath excludes Gradle build output and generated source sets.
func (Analyzer) SkipPath(p string) bool {
	return parsing.InDir(p, "build", ".gradle", "generated")
}

// generatedMarkers are lowercase header phrases of code generators.
var generatedMarkers = [][]byte{
	[]byte("do not edit"), []byte("@generated"), []byte("code generated"), []byte("generated by"),
	[]byte("auto-generated"), []byte("automatically generated"), []byte("this file was generated"),
}

// Skip excludes build output and files whose header marks them as generated.
func (a Analyzer) Skip(f analysis.File) bool {
	if a.SkipPath(f.Path) {
		return true
	}
	head := f.Content
	if len(head) > 512 {
		head = head[:512]
	}
	head = bytes.ToLower(head)
	for _, m := range generatedMarkers {
		if containsWord(head, m) {
			return true
		}
	}
	return false
}

// containsWord reports whether s contains word not followed by a letter, so
// @generated matches but JPA's @GeneratedValue does not.
func containsWord(s, word []byte) bool {
	for i := bytes.Index(s, word); i >= 0; {
		end := i + len(word)
		if end == len(s) || s[end] < 'a' || s[end] > 'z' {
			return true
		}
		next := bytes.Index(s[end:], word)
		if next < 0 {
			return false
		}
		i = end + next
	}
	return false
}

// complexity names this grammar's nodes for cognitive complexity. The grammar
// has no else node (else is an anonymous token of if_expression), so else
// branches add nothing and the if of an "else if" is not counted again; this
// undercounts long else-if chains rather than overcounting them. Labeled jumps
// (break@outer) parse as labeled_expression. call_expression has no function
// field, so recursion is not counted.
var complexity = parsing.ComplexitySyntax{
	Functions: set("function_declaration", "anonymous_function", "lambda_literal", "getter", "setter", "secondary_constructor"),
	Structures: set("if_expression", "for_statement", "while_statement", "do_while_statement", "when_expression",
		"catch_block"),
	ElseClause: "if_expression",
	Logical:    "binary_expression",
	LogicalOps: set("&&", "||"),
	Jumps:      set("labeled_expression"),
	Label:      "label",
}

func set(kinds ...string) map[string]bool {
	m := make(map[string]bool, len(kinds))
	for _, k := range kinds {
		m[k] = true
	}
	return m
}

// Analyze applies every Kotlin rule and idiom to each file.
func (Analyzer) Analyze(ctx context.Context, files []analysis.File) ([]analysis.Finding, error) {
	var findings []analysis.Finding
	for _, f := range files {
		if err := ctx.Err(); err != nil {
			return nil, err
		}
		tree, err := parsing.Parse(parsing.Kotlin, f.Content)
		if err != nil {
			continue
		}
		c := checker{tree: tree, path: f.Path, isTest: analysis.IsTestPath(f.Path), isScript: path.Ext(f.Path) == ".kts"}
		parsing.Walk(tree.Root(), c.visit)
		parsing.Walk(tree.Root(), c.visitIdioms)
		if !c.isTest {
			for _, fn := range parsing.Cognitive(tree, complexity) {
				if fn.Complexity > parsing.CognitiveThreshold {
					c.findings = append(c.findings, analysis.Finding{Rule: "clean.cognitive-complexity", Path: f.Path, Line: fn.Line})
				}
			}
		}
		tree.Close()
		findings = append(findings, c.findings...)
	}
	return findings, nil
}

// frameworkPrefixes map import prefixes to frameworks. Jetpack Compose imports
// (androidx.compose) also count as android, as every androidx import does.
var frameworkPrefixes = []struct{ prefix, framework string }{
	{"android", "android"},
	{"androidx", "android"},
	{"androidx.compose", "jetpack-compose"},
	{"io.ktor", "ktor"},
	{"org.springframework", "spring"},
	{"kotlinx.coroutines", "coroutines"},
	{"org.jetbrains.exposed", "exposed"},
	{"org.koin", "koin"},
	{"dagger.hilt", "hilt"},
}

// Frameworks implements analysis.FrameworkDetector from a file's imports.
func (Analyzer) Frameworks(f analysis.File) []string {
	tree, err := parsing.Parse(parsing.Kotlin, f.Content)
	if err != nil {
		return nil
	}
	defer tree.Close()
	found := map[string]bool{}
	for _, stmt := range parsing.NamedChildren(tree.Root()) {
		if stmt.Kind() != "import" {
			continue
		}
		for _, n := range parsing.NamedChildren(stmt) {
			if n.Kind() != "qualified_identifier" {
				continue
			}
			name := tree.Text(n)
			for _, p := range frameworkPrefixes {
				if name == p.prefix || strings.HasPrefix(name, p.prefix+".") {
					found[p.framework] = true
				}
			}
		}
	}
	out := make([]string, 0, len(found))
	for fw := range found {
		out = append(out, fw)
	}
	sort.Strings(out)
	return out
}

type checker struct {
	tree     *parsing.Tree
	path     string
	isTest   bool
	isScript bool
	findings []analysis.Finding
}

func (c *checker) report(rule string, n *ts.Node) {
	c.findings = append(c.findings, analysis.Finding{Rule: rule, Path: c.path, Line: parsing.Line(n)})
}

// callee returns a call's receiver (nil for a plain call) and the name of the
// function called: x.f() gives (x, "f"), f() gives (nil, "f").
func (c *checker) callee(call *ts.Node) (*ts.Node, string) {
	if call.NamedChildCount() == 0 {
		return nil, ""
	}
	fn := call.NamedChild(0)
	switch fn.Kind() {
	case "identifier":
		return nil, c.tree.Text(fn)
	case "navigation_expression":
		parts := parsing.NamedChildren(fn)
		if len(parts) == 2 && parts[1].Kind() == "identifier" {
			return parts[0], c.tree.Text(parts[1])
		}
	}
	return nil, ""
}

// arguments returns the expressions passed to a call in parentheses.
func arguments(call *ts.Node) []*ts.Node {
	var out []*ts.Node
	for _, child := range parsing.NamedChildren(call) {
		if child.Kind() != "value_arguments" {
			continue
		}
		for _, arg := range parsing.NamedChildren(child) {
			if arg.Kind() == "value_argument" && arg.NamedChildCount() > 0 {
				// A named argument (sql = "...") ends with its value.
				out = append(out, arg.NamedChild(arg.NamedChildCount()-1))
			}
		}
	}
	return out
}

func hasLambda(call *ts.Node) bool {
	for _, child := range parsing.NamedChildren(call) {
		if child.Kind() == "annotated_lambda" {
			return true
		}
	}
	return false
}

// enclosingFunction returns the name of the nearest enclosing named function,
// "" at top level.
func (c *checker) enclosingFunction(n *ts.Node) string {
	for p := n.Parent(); p != nil; p = p.Parent() {
		if p.Kind() == "function_declaration" {
			if name := p.ChildByFieldName("name"); name != nil {
				return c.tree.Text(name)
			}
			return ""
		}
	}
	return ""
}
