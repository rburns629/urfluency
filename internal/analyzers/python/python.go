// Package python analyzes Python source with tree-sitter. It parses files and
// never imports or runs them.
package python

import (
	"bytes"
	"context"
	"strings"

	ts "github.com/tree-sitter/go-tree-sitter"

	"github.com/rburns629/urfluency/internal/analysis"
	"github.com/rburns629/urfluency/internal/parsing"
)

func init() { analysis.Register(Analyzer{}) }

// Analyzer implements analysis.Analyzer for Python.
type Analyzer struct{}

func (Analyzer) Language() string     { return "python" }
func (Analyzer) Extensions() []string { return []string{".py"} }

// Skip excludes virtual environments and generated files such as Django
// migrations.
func (Analyzer) Skip(f analysis.File) bool {
	if parsing.InDir(f.Path, ".venv", "venv", "site-packages", "__pycache__") {
		return true
	}
	head := f.Content
	if len(head) > 512 {
		head = head[:512]
	}
	return bytes.Contains(head, []byte("Generated by Django")) || bytes.Contains(head, []byte("@generated"))
}

var mutableCalls = map[string]bool{"list": true, "dict": true, "set": true, "defaultdict": true}

var literalKinds = map[string]bool{"integer": true, "float": true, "string": true, "concatenated_string": true}

// Analyze applies every Python rule to each file.
func (Analyzer) Analyze(ctx context.Context, files []analysis.File) ([]analysis.Finding, error) {
	var findings []analysis.Finding
	for _, f := range files {
		if err := ctx.Err(); err != nil {
			return nil, err
		}
		tree, err := parsing.Parse(parsing.Python, f.Content)
		if err != nil {
			continue
		}
		c := checker{tree: tree, path: f.Path, isTest: analysis.IsTestPath(f.Path), frameworks: importedFrameworks(tree)}
		parsing.Walk(tree.Root(), c.visit)
		if !c.isTest {
			for _, fn := range parsing.Cognitive(tree, parsing.PythonComplexity) {
				if fn.Complexity > parsing.CognitiveThreshold {
					c.findings = append(c.findings, analysis.Finding{Rule: "clean.cognitive-complexity", Path: f.Path, Line: fn.Line})
				}
			}
		}
		tree.Close()
		findings = append(findings, c.findings...)
	}
	return findings, nil
}

// testFunctionNames are unittest and pytest hooks, which are rarely annotated.
var testFunctionNames = map[string]bool{"setUp": true, "tearDown": true, "setUpClass": true, "tearDownClass": true}

func isTestFunction(name string) bool {
	return strings.HasPrefix(name, "test_") || testFunctionNames[name]
}

type checker struct {
	tree       *parsing.Tree
	path       string
	isTest     bool
	frameworks map[string]bool
	findings   []analysis.Finding
}

func (c *checker) report(rule string, n *ts.Node) {
	c.findings = append(c.findings, analysis.Finding{Rule: rule, Path: c.path, Line: parsing.Line(n)})
}

func (c *checker) visit(n *ts.Node) bool {
	switch n.Kind() {
	case "function_definition":
		c.checkDefaults(n)
		if !c.isTest {
			c.checkAnnotations(n)
		}
	case "except_clause":
		c.checkExcept(n)
	case "comparison_operator":
		if parsing.HasToken(n, "is", "is not") {
			for _, operand := range parsing.NamedChildren(n) {
				if literalKinds[operand.Kind()] {
					c.report("py.is-literal-comparison", n)
					break
				}
			}
		}
	case "call":
		if fn := n.ChildByFieldName("function"); fn != nil && fn.Kind() == "identifier" && c.tree.Text(fn) == "open" && !c.managedOrReturned(n) {
			c.report("py.open-without-with", n)
		}
		c.checkCallSecurity(n)
	case "decorated_definition":
		c.checkDecorated(n)
	case "assignment":
		c.checkDebugSetting(n)
	case "comment":
		if strings.Contains(c.tree.Text(n), "type: ignore") {
			c.report("py.type-ignore", n)
		}
	}
	return true
}

// checkDefaults flags list, dict, set, and comprehension defaults.
func (c *checker) checkDefaults(fn *ts.Node) {
	params := fn.ChildByFieldName("parameters")
	if params == nil {
		return
	}
	for _, p := range parsing.NamedChildren(params) {
		if p.Kind() != "default_parameter" && p.Kind() != "typed_default_parameter" {
			continue
		}
		value := p.ChildByFieldName("value")
		if value == nil {
			continue
		}
		switch value.Kind() {
		case "list", "dictionary", "set", "list_comprehension", "dictionary_comprehension", "set_comprehension":
			c.report("py.mutable-default-argument", value)
		case "call":
			if callee := value.ChildByFieldName("function"); callee != nil && mutableCalls[c.tree.Text(callee)] {
				c.report("py.mutable-default-argument", value)
			}
		}
	}
}

// checkAnnotations flags public, top-level or method functions with an
// unannotated parameter (other than self or cls) or no return annotation.
func (c *checker) checkAnnotations(fn *ts.Node) {
	name := fn.ChildByFieldName("name")
	if name == nil || strings.HasPrefix(c.tree.Text(name), "_") || isTestFunction(c.tree.Text(name)) || nestedInFunction(fn) {
		return
	}
	unannotated := fn.ChildByFieldName("return_type") == nil
	if params := fn.ChildByFieldName("parameters"); params != nil {
		for i, p := range parsing.NamedChildren(params) {
			switch p.Kind() {
			case "identifier":
				if i == 0 && (c.tree.Text(p) == "self" || c.tree.Text(p) == "cls") {
					continue
				}
				unannotated = true
			case "default_parameter", "list_splat_pattern", "dictionary_splat_pattern":
				unannotated = true
			}
		}
	}
	if unannotated {
		c.report("py.unannotated-public-function", fn)
	}
}

func nestedInFunction(n *ts.Node) bool {
	for p := n.Parent(); p != nil; p = p.Parent() {
		if p.Kind() == "function_definition" {
			return true
		}
	}
	return false
}

// checkExcept flags bare except clauses, and broad ones whose body does nothing.
func (c *checker) checkExcept(clause *ts.Node) {
	value := clause.ChildByFieldName("value")
	if value == nil {
		c.report("py.bare-except", clause)
	}
	broad := value == nil
	if value != nil {
		caught := value
		if caught.Kind() == "as_pattern" && caught.NamedChildCount() > 0 {
			caught = caught.NamedChild(0)
		}
		text := c.tree.Text(caught)
		broad = text == "Exception" || text == "BaseException"
	}
	if broad && doesNothing(c.tree, clause) {
		c.report("py.swallowed-exception", clause)
	}
}

// doesNothing reports whether an except clause's block contains only pass or ...
func doesNothing(t *parsing.Tree, clause *ts.Node) bool {
	var block *ts.Node
	for _, child := range parsing.NamedChildren(clause) {
		if child.Kind() == "block" {
			block = child
		}
	}
	if block == nil {
		return false
	}
	for _, stmt := range parsing.NamedChildren(block) {
		switch {
		case stmt.Kind() == "pass_statement", stmt.Kind() == "comment":
		case stmt.Kind() == "expression_statement" && t.Text(stmt) == "...":
		default:
			return false
		}
	}
	return true
}

// managedOrReturned reports whether an open() call is inside a with item or is
// returned to the caller, who then owns closing it.
func (c *checker) managedOrReturned(call *ts.Node) bool {
	for p := call.Parent(); p != nil; p = p.Parent() {
		switch p.Kind() {
		case "with_item", "return_statement":
			return true
		case "function_definition", "module", "lambda":
			return false
		}
	}
	return false
}
