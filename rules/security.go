package rules

// Security rules. Credential findings never include the matched value.
func init() {
	files := []string{"secrets"}
	py := []string{"python"}
	js := []string{"javascript", "typescript"}
	goLang := []string{"go"}
	rotate := "Remove it, rotate the credential now (copies remain in Git history, backups, and anywhere the code was shared), and load it from a secret manager or environment variable."
	Register(
		Rule{ID: "sec.private-key", Category: Security, Languages: files,
			Title: "Private key committed",
			Why:   "Anyone with repository access, now or in the history, can impersonate the key's owner.",
			Focus: rotate},
		Rule{ID: "sec.cloud-credential", Category: Security, Languages: files,
			Title: "Cloud credential committed",
			Why:   "Cloud keys grant direct access to infrastructure and billing, and leaked keys are found by automated scanners within minutes.",
			Focus: rotate},
		Rule{ID: "sec.api-token", Category: Security, Languages: files,
			Title: "API token committed",
			Why:   "Service tokens (GitHub, Slack, Stripe, OpenAI, and others) let anyone act as you on that service.",
			Focus: rotate},
		Rule{ID: "sec.credentials-in-url", Category: Security, Languages: files,
			Title: "Username and password in a URL",
			Why:   "Connection strings with embedded passwords leak through logs, errors, and source control.",
			Focus: "Keep the password out of the URL and inject it from configuration at runtime."},
		Rule{ID: "sec.hardcoded-password", Category: Security, Languages: files,
			Title: "Hard-coded password or secret",
			Why:   "A secret in source code is shared with everyone who can read the code and cannot be rotated without a release.",
			Focus: rotate},

		Rule{ID: "py.sql-string-built", Category: Security, Languages: py,
			Title: "SQL built from formatted strings",
			Why:   "f-strings, % formatting, .format(), or + in a query let input change the SQL itself (SQL injection).",
			Focus: "Pass values as query parameters (cursor.execute(sql, params)) or use the ORM."},
		Rule{ID: "py.eval-exec", Category: Security, Languages: py,
			Title: "eval or exec on dynamic input",
			Why:   "Evaluating strings runs arbitrary code if any part comes from outside.",
			Focus: "Use ast.literal_eval for data, or a dispatch table instead of generated code."},
		Rule{ID: "py.unsafe-deserialization", Category: Security, Languages: py,
			Title: "Unsafe deserialization",
			Why:   "pickle, marshal, and yaml.load without SafeLoader can execute code embedded in the data.",
			Focus: "Use JSON, or yaml.safe_load, for anything that crosses a trust boundary."},
		Rule{ID: "py.shell-injection", Category: Security, Languages: py,
			Title: "Shell command built from dynamic input",
			Why:   "shell=True or os.system with a built string lets input inject extra shell commands.",
			Focus: "Pass an argument list to subprocess.run without shell=True."},
		Rule{ID: "py.tls-verify-disabled", Category: Security, Languages: py,
			Title: "TLS certificate verification disabled",
			Why:   "verify=False accepts any certificate, so traffic can be intercepted or altered.",
			Focus: "Keep verification on; configure a custom CA bundle if you need one."},

		Rule{ID: "js.eval", Category: Security, Languages: js,
			Title: "eval, new Function, or string timers",
			Why:   "Running strings as code executes anything an attacker can get into them.",
			Focus: "Use functions and data structures instead of generated code."},
		Rule{ID: "js.child-process-injection", Category: Security, Languages: js,
			Title: "Shell command built from dynamic input",
			Why:   "exec and execSync run a shell, so interpolated input can inject commands.",
			Focus: "Use execFile or spawn with an argument array."},
		Rule{ID: "js.sql-string-built", Category: Security, Languages: js,
			Title: "SQL built from template strings or concatenation",
			Why:   "Interpolating values into a query string allows SQL injection.",
			Focus: "Use parameter placeholders, or the driver's tagged sql`` template."},
		Rule{ID: "js.html-injection", Category: Security, Languages: js,
			Title: "Dynamic HTML written into the page",
			Why:   "innerHTML, outerHTML, insertAdjacentHTML, and document.write with dynamic values allow cross-site scripting.",
			Focus: "Set textContent, or sanitize with a vetted library such as DOMPurify."},
		Rule{ID: "js.tls-verify-disabled", Category: Security, Languages: js,
			Title: "TLS certificate verification disabled",
			Why:   "rejectUnauthorized: false or NODE_TLS_REJECT_UNAUTHORIZED=0 accepts any certificate.",
			Focus: "Keep verification on; supply a custom CA if needed."},

		Rule{ID: "go.sql-string-built", Category: Security, Languages: goLang,
			Title: "SQL built with fmt.Sprintf or concatenation",
			Why:   "Formatting values into a query string allows SQL injection.",
			Focus: "Use placeholders ($1 or ?) and pass values as arguments to Query or Exec."},
		Rule{ID: "go.shell-command", Category: Security, Languages: goLang,
			Title: "Shell command built from dynamic input",
			Why:   "exec.Command(\"sh\", \"-c\", built) lets input inject shell commands.",
			Focus: "Call the program directly with separate arguments."},
		Rule{ID: "go.tls-insecure-skip-verify", Category: Security, Languages: goLang,
			Title: "TLS certificate verification disabled",
			Why:   "InsecureSkipVerify: true accepts any certificate, so connections can be intercepted.",
			Focus: "Remove it; configure RootCAs for private certificate authorities."},
	)
}
