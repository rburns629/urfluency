package rules

func init() {
	java := []string{"java"}
	Register(
		Rule{ID: "java.sql-string-built", Category: Security, Languages: java,
			Title: "SQL built by string concatenation",
			Why:   "Concatenating values into SQL or JPQL passed to execute, prepareStatement, or createQuery lets input rewrite the query (SQL injection).",
			Focus: "Use PreparedStatement placeholders or JPA parameters (setParameter) and pass values separately."},
		Rule{ID: "java.unsafe-deserialization", Category: Security, Languages: java,
			Title: "Unfiltered Java deserialization",
			Why:   "ObjectInputStream and XMLDecoder instantiate whatever classes the data names, so untrusted bytes can run gadget chains on the classpath.",
			Focus: "Use a data format such as JSON, or install an ObjectInputFilter that allowlists the expected classes."},
		Rule{ID: "java.command-built", Category: Security, Languages: java,
			Title: "Command built by string concatenation",
			Why:   "Runtime.exec with a concatenated string, or a shell (sh -c) given a concatenated command, lets input add arguments or whole commands.",
			Focus: "Pass the program and each argument separately to ProcessBuilder, without a shell, and validate the inputs."},
		Rule{ID: "java.trust-all-certificates", Category: Security, Languages: java,
			Title: "TLS certificate or hostname checks disabled",
			Why:   "An empty checkServerTrusted or a HostnameVerifier that always returns true accepts any server, which enables man-in-the-middle attacks.",
			Focus: "Use the default trust manager and verifier; for private CAs, load them into a dedicated TrustStore."},
		Rule{ID: "java.empty-catch", Category: CleanCode, Languages: java,
			Title: "Empty catch block",
			Why:   "Catching an exception and doing nothing turns failures into silent wrong behavior that is hard to trace.",
			Focus: "Handle, log, or rethrow the exception; if ignoring it is intended, name it ignored and say why in a comment."},
		Rule{ID: "java.print-stack-trace", Category: CleanCode, Languages: java,
			Title: "printStackTrace instead of a logger",
			Why:   "e.printStackTrace() writes to stderr with no level, timestamp, or context, and bypasses the application's logging configuration.",
			Focus: "Log the exception with a logger, such as log.error(\"message\", e), or rethrow it."},
		Rule{ID: "java.raw-type", Category: TypeSafety, Languages: java,
			Title: "Generic type used without type arguments",
			Why:   "Raw List, Map, and similar types turn off generic checking, so wrong element types fail at runtime with ClassCastException.",
			Focus: "Declare the type arguments, such as List<String>, and use the diamond (new ArrayList<>()) on creation."},
		Rule{ID: "java.string-equality", Category: LanguageProficiency, Languages: java,
			Title: "String compared with == or !=",
			Why:   "== compares object identity, not contents, so equal strings built at runtime compare as different.",
			Focus: "Use \"literal\".equals(value) or Objects.equals(a, b)."},
	)
	Register(
		idiom("java.idiom.try-with-resources", "try-with-resources", "Closes streams, connections, and locks on every path, including exceptions.", java...),
		idiom("java.idiom.streams", "Stream pipelines", "Transforms collections declaratively with stream(), map, filter, and collect instead of manual loops.", java...),
		idiom("java.idiom.optional", "Optional", "Makes a possibly missing value explicit in the type instead of returning null.", java...),
		idiom("java.idiom.records", "Records", "Declares immutable data carriers with equals, hashCode, and toString generated by the compiler.", java...),
		idiom("java.idiom.var", "var for local variables", "Lets the compiler infer obvious local types, removing repetition without losing static typing.", java...),
		idiom("java.idiom.switch-expression", "Arrow switch", "Uses case -> rules, which cannot fall through and can yield a value.", java...),
		idiom("java.idiom.lambdas", "Lambdas and method references", "Passes behavior concisely instead of anonymous classes.", java...),
		idiom("java.idiom.bounded-generics", "Bounded generics", "Uses extends and super bounds so generic code accepts exactly the types it can handle.", java...),
		idiom("java.idiom.sealed-types", "Sealed types", "Restricts which classes may extend a type, so the compiler can check that every case is handled.", java...),
		idiom("java.idiom.pattern-matching", "Pattern matching instanceof", "Tests and casts in one step, removing a separate, error-prone cast.", java...),
	)
}
